/* The mascot drawn once into the firmware's framebuffer at device start, so the boot screen is not only a
 * spinner on black. Geometry, decoding and blending only: plain C over a caller-supplied pointer, no WDK header,
 * no allocation, no floating point. display.c runs it on the POST framebuffer that DxgkDdiStartDevice mapped,
 * driver\kmd\test\boot_logo_test.c runs it on an array.
 *
 * The destination is the firmware's surface, which the driver has already proved to be 32 bits a pixel in
 * D3DDDIFMT_X8R8G8B8 or D3DDDIFMT_A8R8G8B8 (display.c, IsPostFormatSupported): byte order B, G, R, X in memory.
 * Every coordinate here is in that surface, never in the monitor's timing. Where the firmware scaled a smaller
 * surface up to a larger timing (BD-155, a 800x600 surface on a 1920x1200 panel), the display pipe scales what
 * this code draws with the rest of the picture, so the mascot keeps the same share of the screen.
 *
 * Nothing here reads the destination outside the rectangle it places, and nothing writes outside it. An asset
 * that does not verify, or a surface the picture does not fit in, draws no pixel at all.
 *
 * docs/design/boot-logo.md has the design and the contract this sits under.
 */
#pragma once

/* One colour of the palette: straight (not premultiplied) alpha, in the destination's byte order. */
typedef struct BC250_LOGO_COLOR {
    unsigned char B, G, R, A;
} BC250_LOGO_COLOR;

/* A picture generated by tools/win/make_boot_logo_asset.py. Data holds Height rows; a row is a sequence of
 * (count, index) byte pairs with count 1..255, ended by a single zero byte. The counts of a row add up to
 * exactly Width. Index 0 of the palette is the fully transparent colour. */
typedef struct BC250_BOOT_LOGO {
    unsigned long Width, Height;
    unsigned long PaletteCount;
    unsigned long DataBytes;
    const BC250_LOGO_COLOR* Palette;
    const unsigned char* Data;
} BC250_BOOT_LOGO;

/* The destination surface and where the mascot is wanted on it. AnchorPermille is the vertical centre of the
 * picture in thousandths of Height, so that the mascot sits above the Windows spinner rather than under it;
 * 350 is the default and 100..900 the range the caller may ask for. */
typedef struct BC250_BOOT_LOGO_TARGET {
    unsigned long Width, Height, Pitch;
    unsigned long AnchorPermille;
} BC250_BOOT_LOGO_TARGET;

typedef struct BC250_BOOT_LOGO_PLACEMENT {
    unsigned long Scale;                    /* whole-number enlargement, 1..3 */
    unsigned long Left, Top;                /* top left corner, in destination pixels */
    unsigned long DrawWidth, DrawHeight;    /* Width*Scale, Height*Scale */
} BC250_BOOT_LOGO_PLACEMENT;

typedef enum BC250_BOOT_LOGO_RESULT {
    Bc250LogoDrawn = 0,
    Bc250LogoBadArgument = 1,       /* a null pointer, or a surface this code cannot address */
    Bc250LogoBadAsset = 2,          /* the run data does not describe exactly Width x Height pixels */
    Bc250LogoNoRoom = 3             /* the picture does not fit on this surface, even unscaled */
} BC250_BOOT_LOGO_RESULT;

/* The asset's own self-check: every row covers exactly Width pixels, every index is inside the palette, and the
 * run data ends exactly at DataBytes. Returns Bc250LogoDrawn when the asset is sound. */
BC250_BOOT_LOGO_RESULT Bc250BootLogoVerify(const BC250_BOOT_LOGO* Logo);

/* Where the picture goes. The enlargement is Height/600 brought inside 1..3 and then lowered until the picture
 * fits in the surface's width and in the band the picture may use.
 *
 * The band is the top BC250_LOGO_BOTTOM_PERMILLE thousandths of the surface. Windows draws its own ring below
 * that line and the ring must stay untouched (the mascot goes in the logo area above the ring, never over
 * it), so no pixel of the picture is ever placed below the line, whatever AnchorPermille asks
 * for. Placement is cleared unless the result is Bc250LogoDrawn. */
#define BC250_LOGO_BOTTOM_PERMILLE 550ul
BC250_BOOT_LOGO_RESULT Bc250BootLogoPlace(const BC250_BOOT_LOGO* Logo, const BC250_BOOT_LOGO_TARGET* Target,
                                          BC250_BOOT_LOGO_PLACEMENT* Placement);

/* Verify, place and draw, in that order. Pixels is the first byte of the destination surface and must address
 * at least Pitch * Height bytes. Source over destination: a fully opaque source pixel is stored without reading
 * the destination, a fully transparent one is skipped, and only the edge of the figure is blended. Writes
 * nothing at all unless the result is Bc250LogoDrawn; Written, when given, counts the pixels it changed. */
BC250_BOOT_LOGO_RESULT Bc250BootLogoDraw(void* Pixels, const BC250_BOOT_LOGO* Logo,
                                         const BC250_BOOT_LOGO_TARGET* Target, unsigned long* Written);

/* The text of a result, for the driver's log. Never null. */
const char* Bc250BootLogoResultText(BC250_BOOT_LOGO_RESULT Result);

/* The picture this driver ships: boot_logo_asset.inc, generated from the mascot the control application and the
 * installer already show (tools/win/amdgpu_wddm_control/art/nagi, its PROVENANCE.md). Never null, and the same
 * pointer on every call. */
const BC250_BOOT_LOGO* Bc250BootLogoAsset(void);

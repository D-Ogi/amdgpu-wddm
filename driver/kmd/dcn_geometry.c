static int Put(unsigned long* word, unsigned long mask, unsigned long value)
{
    unsigned long packed = Bc250DispField(mask, value);
    if (Bc250DispGet(packed, mask) != value) return 0;
    *word |= packed;
    return 1;
}
#define PUT(word, mask, value) do { if (!Put(&Plan->Words[word], mask, value)) goto refuse; } while (0)


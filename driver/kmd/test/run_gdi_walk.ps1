# Host test of the command-buffer walk of DxgkDdiRenderGdi (driver\kmd\gdi_walk.c), against an
# inaccessible page. It compiles the production walk as it is, with no copy of the code and no
# second version of the WDK types: the GDI block of the WDK's own shared\d3dkmddi.h is sliced out
# into a header named gdi_walk_ddi.h, which is force-included ahead of everything. That header
# defines the include guard of driver\kmd\gdi_walk_ddi.h, so the driver's own prelude (ntifs.h,
# windef.h, dispmprt.h) is skipped and the same C file compiles in user mode.
#
# Review r1 of 2026-10-14: the walk read the union member the opcode names before it had checked
# CommandSize, so a buffer that ends inside its last command was read past CommandLength. The test
# puts every command at the end of a committed page with the next page inaccessible, so such a read
# is an access violation. gdi_walk_test.c starts with the positive control on that page.
#
#   pwsh driver\kmd\test\run_gdi_walk.ps1 -Out P:\BC-250\scratch\gdi-hw\walk
#
# Everything is written under -Out, never into the repository and never onto drive C:.

param(
    [string]$Root = $(if ($env:BC250_ROOT) { $env:BC250_ROOT } else { (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path }),
    [string]$Out = "$Root\scratch\gdi-walk",
    [string]$Kits = "$Root\toolchain\nuget",
    [string]$KitVersion = '10.0.26100.0'
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$kmd = Split-Path -Parent $here
$wdk = Join-Path $Kits 'microsoft.windows.wdk.x64\c'
$sdk = Join-Path $Kits 'microsoft.windows.sdk.cpp\c'
$sdklib = Join-Path $Kits 'microsoft.windows.sdk.cpp.x64\c'

$vs = & "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" -latest -products * -property installationPath
$msvc = Get-ChildItem (Join-Path $vs 'VC\Tools\MSVC') -Directory | Sort-Object Name | Select-Object -Last 1
$bin = Join-Path $msvc.FullName 'bin\Hostx64\x64'

$obj = Join-Path $Out 'obj'
$inc = Join-Path $Out 'include'
New-Item -ItemType Directory -Force $Out, $obj, $inc | Out-Null
Remove-Item "$obj\*.obj" -Force -ErrorAction SilentlyContinue

function Invoke-Tool([string]$exe, [string[]]$argv) {
    & $exe @argv | ForEach-Object { if ($_ -notmatch '^\s*$|^Microsoft|^Copyright|^\S+\.c$') { Write-Host "  $_" } }
    if ($LASTEXITCODE -ne 0) { throw "$(Split-Path -Leaf $exe) failed ($LASTEXITCODE)" }
}

# The slice: from the first GDI declaration to the end of DXGK_RENDERKM_COMMAND, found by its own
# text and not by line numbers, so a kit update either slices the same block or stops the test.
$source = Join-Path $wdk "Include\$KitVersion\shared\d3dkmddi.h"
$lines = Get-Content $source
$first = ($lines | Select-String -SimpleMatch 'typedef enum _DXGK_GDIROP_BITBLT' | Select-Object -First 1).LineNumber
$last = ($lines | Select-String -SimpleMatch '} DXGK_RENDERKM_COMMAND;' | Select-Object -First 1).LineNumber
if (-not $first -or -not $last -or $last -le $first) { throw "the GDI block was not found in $source" }
$block = $lines[($first - 1)..($last - 1)]
foreach ($name in @('DXGK_GDIARG_BITBLT', 'DXGK_GDIARG_COLORFILL', 'DXGK_GDIARG_CLEARTYPEBLEND',
                    'DXGK_RENDERKM_OPERATION', 'DXGK_RENDERKM_COMMAND')) {
    if (-not ($block | Select-String -SimpleMatch "} $name;")) { throw "the slice has no $name" }
}
$header = @(
    '/* Generated by driver\kmd\test\run_gdi_walk.ps1. Do not edit, do not commit.',
    " * The GDI command block of $source,",
    " * lines $first to $last, with the kernel types replaced by the user-mode ones of windows.h.",
    ' * It defines the include guard of driver\kmd\gdi_walk_ddi.h, so that the production gdi_walk.c',
    ' * compiles in user mode without a change. */',
    '#ifndef BC250_GDI_WALK_DDI_H',
    '#define BC250_GDI_WALK_DDI_H',
    '#include <windows.h>',
    '') + $block + @('', '#endif /* BC250_GDI_WALK_DDI_H */')
$slice = Join-Path $inc 'gdi_walk_ddi.h'
Set-Content -Path $slice -Value $header -Encoding utf8
Write-Host "slice: $((Get-Item $slice).Length) bytes from d3dkmddi.h lines $first-$last"

$env:TEMP = Join-Path $Root 'scratch\tmp'; $env:TMP = $env:TEMP
$env:INCLUDE = ''
$env:LIB = ''

$incUser = @("/I$inc", "/I$kmd", "/I$sdk\Include\$KitVersion\ucrt", "/I$sdk\Include\$KitVersion\um",
    "/I$sdk\Include\$KitVersion\shared", "/I$($msvc.FullName)\include")

Write-Host 'compile and link (host, the production walk and the sliced WDK types)'
Invoke-Tool (Join-Path $bin 'cl.exe') (@('/nologo', '/TC', '/W4', '/WX', '/Od', '/Zi', "/FI$slice",
      '/wd4201', '/wd4214') + $incUser +
    @("/Fo$obj\", "/Fd$obj\cl.pdb", "/Fe$Out\gdi_walk_test.exe") +
    @((Join-Path $kmd 'gdi_walk.c'), (Join-Path $kmd 'gdi_render.c'), (Join-Path $here 'gdi_walk_test.c')) +
    @('/link', "/LIBPATH:$sdklib\ucrt\x64", "/LIBPATH:$sdklib\um\x64", "/LIBPATH:$($msvc.FullName)\lib\x64"))

Write-Host 'run'
& "$Out\gdi_walk_test.exe"
$code = $LASTEXITCODE

# The same file with the kernel flags and the real WDK header, which is how the driver builds it.
Write-Host 'compile-check (kernel flags, the driver prelude, no link)'
$kernFlags = @('/nologo', '/c', '/TC', '/kernel', '/GS-', '/W4', '/WX', '/O2', '/Zi', '/Zp8', '/GF', '/Gy',
    '/wd4201', '/wd4214',
    '/D_AMD64_', '/DAMD64', '/D_WIN64', '/DWINNT=1', '/DNTDDI_VERSION=0x0A00000C', '/D_WIN32_WINNT=0x0A00', '/DNDEBUG',
    "/I$wdk\Include\$KitVersion\km", "/I$wdk\Include\$KitVersion\km\crt", "/I$wdk\Include\$KitVersion\shared",
    "/I$sdk\Include\$KitVersion\shared", "/I$sdk\Include\$KitVersion\um",
    "/I$kmd", "/Fo$obj\kernel-", "/Fd$obj\clkernel.pdb")
Invoke-Tool (Join-Path $bin 'cl.exe') ($kernFlags + @((Join-Path $kmd 'gdi_walk.c')))

Write-Host ''
Write-Host "gdi_walk_test.exe exit code $code"
exit $code

# Host test for BD-410 stage 1: the OPM answers of opm_policy.h and the query log rule of query_interface_policy.h.
# No lab access. BC250_ROOT is the workspace root: the environment variable, else the parent directory of this
# repository.
# Steps:
#   1. opm_wdk_guids.h is generated from every DEFINE_GUID of the WDK's km/dispmprt.h, so that the test asks the
#      policy with the WDK's own GUIDs (no GUID is typed by hand).
#   2. The two headers are copied next to the build (/I of the copy comes first). A negative control changes the
#      copy and never the tree.
#   3. A kernel probe compiles both headers with the KMD's compiler (the WDK's MSVC, kernel flags) and binds each
#      constant of the headers to its WDK name with C_ASSERT, so that a wrong status value fails here.
#   4. The host test is built with clang-cl 23.1.4 from the workspace toolchain (named by path, no fallback) and run.
# Negative controls (tools\quality\quick.ps1, Fails): each must fail the test by a FAIL line.
#   -Mutation any-guid        the query answer does not compare the GUID
#   -Mutation any-version     the query answer does not compare the version
#   -Mutation any-size        the query answer does not compare the size
#   -Mutation stale-handle    a destroy does not advance the slot's generation, so an old handle matches a new output
#   -Mutation refuse-success  a refused OPM call answers STATUS_SUCCESS
#   -Mutation log-every       the query log writes a line for every request
param(
    [string]$Root = $(if ($env:BC250_ROOT) { $env:BC250_ROOT } else { (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path }),
    [string]$Out = "$Root\scratch\build\opm-policy",
    [string]$Kits = "$Root\toolchain\nuget",
    [string]$KitVersion = '10.0.26100.0',
    [string]$Llvm = "$Root\toolchain\llvm-23.1.4-win64",
    [ValidateSet('none', 'any-guid', 'any-version', 'any-size', 'stale-handle', 'refuse-success', 'log-every')]
    [string]$Mutation = 'none'
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$kmd = Split-Path -Parent $here
$wdk = Join-Path $Kits 'microsoft.windows.wdk.x64\c'
$sdk = Join-Path $Kits 'microsoft.windows.sdk.cpp\c'
$sdklib = Join-Path $Kits 'microsoft.windows.sdk.cpp.x64\c'
if ($Mutation -ne 'none' -and -not $PSBoundParameters.ContainsKey('Out')) { $Out = "$Out-$Mutation" }
$env:TEMP = Join-Path $Root 'scratch\tmp'; $env:TMP = $env:TEMP
$src = Join-Path $Out 'src'
$obj = Join-Path $Out 'obj'
New-Item -ItemType Directory -Force $Out, $src, $obj, $env:TEMP | Out-Null
Remove-Item "$obj\*.obj" -Force -ErrorAction SilentlyContinue

$clang = Join-Path $Llvm 'bin\clang-cl.exe'
if (-not (Test-Path -LiteralPath $clang)) { throw "clang-cl not found: $clang" }
$clangVersion = @(& $clang --version)
if ($LASTEXITCODE -ne 0 -or $clangVersion[0] -notmatch 'clang version 23\.1\.4\b') { throw "clang-cl 23.1.4 expected: $($clangVersion[0])" }
Write-Host "host compiler: $clang"
Write-Host "  $($clangVersion[0])"
$vs = & "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" -latest -products * -property installationPath
$msvc = Get-ChildItem (Join-Path $vs 'VC\Tools\MSVC') -Directory | Sort-Object Name | Select-Object -Last 1
$bin = Join-Path $msvc.FullName 'bin\Hostx64\x64'

function Invoke-Tool([string]$exe, [string[]]$argv) {
    & $exe @argv | ForEach-Object { if ($_ -notmatch '^\s*$|^Microsoft|^Copyright|^\S+\.c$') { Write-Host "  $_" } }
    if ($LASTEXITCODE -ne 0) { throw "$(Split-Path -Leaf $exe) failed ($LASTEXITCODE)" }
}

# 1. The WDK's GUIDs. DEFINE_GUID(name, l, w1, w2, b1..b8): the in-memory bytes are l, w1 and w2 little-endian,
# then b1..b8 in order.
$dispmprt = Join-Path $wdk "Include\$KitVersion\km\dispmprt.h"
$hex = '(0[xX][0-9A-Fa-f]+)'
$pattern = "DEFINE_GUID\(\s*(\w+)\s*,\s*$hex\s*,\s*$hex\s*,\s*$hex" + ("\s*,\s*$hex" * 8) + '\s*\)'
$rows = [System.Collections.Generic.List[string]]::new()
$seen = @{}
foreach ($m in [regex]::Matches((Get-Content -LiteralPath $dispmprt -Raw), $pattern)) {
    $name = $m.Groups[1].Value
    if ($seen.ContainsKey($name)) { continue }
    $seen[$name] = $true
    $n = @(2..12 | ForEach-Object { [Convert]::ToUInt64($m.Groups[$_].Value.Substring(2), 16) })
    $bytes = [System.Collections.Generic.List[uint64]]::new()
    foreach ($s in 0, 8, 16, 24) { $bytes.Add(($n[0] -shr $s) -band 0xFF) }
    foreach ($w in $n[1], $n[2]) { $bytes.Add($w -band 0xFF); $bytes.Add(($w -shr 8) -band 0xFF) }
    foreach ($b in $n[3..10]) { $bytes.Add($b -band 0xFF) }
    $rows.Add("    {`"$name`", {" + (($bytes | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ') + '}},')
}
if ($rows.Count -lt 10 -or -not $seen.ContainsKey('GUID_DEVINTERFACE_OPM')) { throw "dispmprt.h gave $($rows.Count) GUIDs" }
$guids = @("// Generated by run_opm_policy.ps1 from $dispmprt. Do not edit.", '#pragma once',
    "#define OPM_WDK_GUID_COUNT $($rows.Count)u",
    'static const struct { const char* Name; unsigned char Bytes[16]; } OpmWdkGuids[] = {') + $rows + @('};', '')
[IO.File]::WriteAllText((Join-Path $src 'opm_wdk_guids.h'), ($guids -join "`n"))
Write-Host "WDK GUIDs: $($rows.Count) from km\dispmprt.h"

# 2. The headers under test, as copies.
$mutations = @{
    'any-guid'       = @('opm_policy.h', 'if (InterfaceType == 0 || !OpmGuidEqual(InterfaceType, OpmGuid)) return OPM_STATUS_NOT_SUPPORTED;',
                         'if (InterfaceType == 0 || !OpmGuid) return OPM_STATUS_NOT_SUPPORTED;')
    'any-version'    = @('opm_policy.h', 'if (Version != V1Version || Size < V1Size || Interface == 0)',
                         'if (Size < V1Size || Interface == 0 || V1Version == 0xFFFFFFFFu || Version == 0xFFFFFFFFu)')
    'any-size'       = @('opm_policy.h', 'if (Version != V1Version || Size < V1Size || Interface == 0)',
                         'if (Version != V1Version || Interface == 0 || V1Size == 0xFFFFFFFFu || Size == 0xFFFFFFFFu)')
    'stale-handle'   = @('opm_policy.h', '    Outputs->Generation[slot]++;', '    (void)Outputs->Generation[slot];')
    'refuse-success' = @('opm_policy.h', '    Outputs->Refused++;', '    Outputs->Refused++; if (Outputs->Refused) return OPM_STATUS_SUCCESS;')
    'log-every'      = @('query_interface_policy.h', '        if (same) return QI_LOG_NONE;', '        if (same) return QI_LOG_LINE;')
}
foreach ($name in 'opm_policy.h', 'query_interface_policy.h') {
    $text = Get-Content -LiteralPath (Join-Path $kmd $name) -Raw
    if ($Mutation -ne 'none' -and $mutations[$Mutation][0] -eq $name) {
        $anchor = $mutations[$Mutation][1]; $replacement = $mutations[$Mutation][2]
        $hits = $text.Split(@($anchor), [StringSplitOptions]::None).Count - 1
        if ($hits -ne 1) { throw "negative control $Mutation : its line matched $hits times, once expected" }
        $text = $text.Replace($anchor, $replacement)
        Write-Host "mutation $Mutation : $($replacement.Trim())"
    }
    [IO.File]::WriteAllText((Join-Path $src $name), $text)
}

$env:INCLUDE = ''; $env:LIB = ''; $env:CL = $null; $env:_CL_ = $null

# 3. The kernel probe: the KMD's compiler and the WDK's names. Tree headers, not the mutated copies: the probe binds
# the constants, and no control changes a constant.
Write-Host 'compile-check (WDK MSVC, kernel flags, the headers against dispmprt.h and ntstatus.h)'
$probe = Join-Path $Out 'opm_policy_kernel.c'
[IO.File]::WriteAllText($probe, @'
#define DXGKDDI_INTERFACE_VERSION 0xE003
#include <ntifs.h>
#include <windef.h>
#include <dispmprt.h>
#include "opm_policy.h"
#include "query_interface_policy.h"
C_ASSERT(OPM_STATUS_SUCCESS == STATUS_SUCCESS);
C_ASSERT(OPM_STATUS_NOT_SUPPORTED == STATUS_NOT_SUPPORTED);
C_ASSERT(OPM_STATUS_NO_MEMORY == STATUS_NO_MEMORY);
C_ASSERT(OPM_STATUS_INVALID_TARGET == STATUS_GRAPHICS_INVALID_VIDEO_PRESENT_TARGET);
C_ASSERT(OPM_STATUS_OPM_NOT_SUPPORTED == STATUS_GRAPHICS_OPM_NOT_SUPPORTED);
C_ASSERT(OPM_STATUS_OPM_INVALID_HANDLE == STATUS_GRAPHICS_OPM_INVALID_HANDLE);
C_ASSERT(OPM_SEMANTICS_COPP == DXGKMDT_OPM_VOS_COPP_SEMANTICS);
C_ASSERT(OPM_SEMANTICS_OPM == DXGKMDT_OPM_VOS_OPM_SEMANTICS);
C_ASSERT(sizeof(GUID) == 16);
/* The stand-ins of the host test (opm_policy_test.c V1_SIZE, V1_VERSION). */
C_ASSERT(sizeof(DXGK_OPM_INTERFACE) == 104);
C_ASSERT(DXGK_OPM_INTERFACE_VERSION_1 == 1);
/* A HANDLE carries every value OpmHandleOf gives (32 bits). */
C_ASSERT(sizeof(HANDLE) >= 4);
NTSTATUS OpmPolicyProbe(const QUERY_INTERFACE* Q, OPM_OUTPUTS* T, QI_LOG* L)
{
    unsigned long long h = 0;
    NTSTATUS s = (NTSTATUS)OpmQueryInterfaceAnswer(Q->InterfaceType, &GUID_DEVINTERFACE_OPM, Q->Size, Q->Version,
                                                   Q->Interface, sizeof(DXGK_OPM_INTERFACE), DXGK_OPM_INTERFACE_VERSION_1);
    (void)QiLogNote(L, Q->InterfaceType, Q->Size, Q->Version, s);
    if (NT_SUCCESS(s)) s = (NTSTATUS)OpmCreate(T, 1u, 1u, OPM_SEMANTICS_OPM, &h);
    if (NT_SUCCESS(s)) s = (NTSTATUS)OpmDestroy(T, h);
    return NT_SUCCESS(s) ? (NTSTATUS)OpmRefuse(T) : s;
}
'@)
$kernFlags = @('/nologo', '/c', '/TC', '/kernel', '/GS-', '/W4', '/WX', '/O2', '/Zi', '/Zp8', '/GF', '/Gy',
    '/D_AMD64_', '/DAMD64', '/D_WIN64', '/DWINNT=1', '/DNTDDI_VERSION=0x0A00000C', '/D_WIN32_WINNT=0x0A00', '/DNDEBUG',
    "/I$wdk\Include\$KitVersion\km", "/I$wdk\Include\$KitVersion\km\crt", "/I$wdk\Include\$KitVersion\shared",
    "/I$sdk\Include\$KitVersion\shared", "/I$kmd", "/Fo$obj\kernel-", "/Fd$obj\clkernel.pdb")
Invoke-Tool (Join-Path $bin 'cl.exe') ($kernFlags + @($probe))

# 4. The host test.
Write-Host 'compile and link (host, clang-cl, no WDK header)'
$incHost = @("/I$src", "/imsvc$sdk\Include\$KitVersion\ucrt", "/imsvc$sdk\Include\$KitVersion\um",
    "/imsvc$sdk\Include\$KitVersion\shared", "/imsvc$($msvc.FullName)\include")
Invoke-Tool $clang (@('/nologo', '--target=x86_64-pc-windows-msvc', '/TC', '/W4', '/WX', '/Od', '/Zi', '/MT',
    '-fuse-ld=lld') + $incHost + @("/Fo$obj\", "/Fe$Out\opm_policy_test.exe", (Join-Path $here 'opm_policy_test.c')) +
    @('/link', "/LIBPATH:$sdklib\ucrt\x64", "/LIBPATH:$sdklib\um\x64", "/LIBPATH:$($msvc.FullName)\lib\x64"))

. "$here\host_native.ps1"
Exit-NativeTest "$Out\opm_policy_test.exe"

static uint8_t g_cbpCodeNumIntra[48];
static uint8_t g_cbpCodeNumInter[48];
static bool g_derivedReady = false;

void InitDerivedTables()
{
    if (g_derivedReady) {
        return;
    }
    for (uint32_t i = 0; i < 48; ++i) {
        g_cbpCodeNumIntra[kCbpIntraFromCodeNum[i]] = static_cast<uint8_t>(i);
        g_cbpCodeNumInter[kCbpInterFromCodeNum[i]] = static_cast<uint8_t>(i);
    }
    g_derivedReady = true;
}

uint32_t CbpToCodeNum(uint32_t cbp, bool intra)
{
    InitDerivedTables();
    // The coded block pattern of a 4:2:0 macroblock is cbpLuma + 16 * cbpChroma, so 0..47. A mask of
    // 47 would silently drop bit 4 (47 is 0b101111): the index has to be range checked instead.
    const uint32_t index = (cbp < 48u) ? cbp : 0u;
    return intra ? g_cbpCodeNumIntra[index] : g_cbpCodeNumInter[index];
}


# ---- C and C++ source text -------------------------------------------------------------------------------------

def clean(text: str) -> str:
    """Comments become spaces, string and character literals become empty quotes. Line breaks stay."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(re.sub(r"[^\n]", " ", text[i:j]))
            i = j
        elif c == '"' or (c == "'" and not (i and (text[i - 1].isalnum()) and i + 1 < n and text[i + 1].isdigit())):
            q = c
            j = i + 1
            while j < n and text[j] != q:
                if text[j] == "\\":
                    j += 1
                if j < n and text[j] == "\n":
                    break
                j += 1
            body = text[i + 1:j]
            out.append(q + re.sub(r"[^\n]", " ", body) + (q if j < n else ""))
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


DEFINE = re.compile(r"^[ \t]*#[ \t]*(define|undef)[ \t]+(\w+)(\([^)]*\))?(.*)$")


def preprocess(text: str) -> str:
    """Join continuation lines (keeping the line count), blank every directive, and expand the macros that the
    file itself defines, in file order, with #undef honoured. No conditional is evaluated."""
    lines = text.split("\n")
    joined: list[str] = []
    i = 0
    while i < len(lines):
        line, extra = lines[i], 0
        while line.endswith("\\") and i + 1 < len(lines):
            i += 1
            extra += 1
            line = line[:-1] + " " + lines[i]
        joined.append(line)
        joined.extend([""] * extra)
        i += 1
    macros: dict[str, tuple[list[str] | None, str]] = {}
    out = []
    for line in joined:
        m = DEFINE.match(line)
        if m:
            if m.group(1) == "define":
                params = None
                if m.group(3) is not None:
                    params = [p.strip() for p in m.group(3)[1:-1].split(",") if p.strip()]
                macros[m.group(2)] = (params, m.group(4).strip())
            else:
                macros.pop(m.group(2), None)
            out.append("")
        elif line.lstrip().startswith("#"):
            out.append("")
        else:
            out.append(expand(line, macros))
    return "\n".join(out)


def split_args(text: str) -> list[str]:
    args, depth, cur = [], 0, []
    for ch in text:
        if ch in "([{<" and ch != "<":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    args.append("".join(cur).strip())
    return args


def match_paren(text: str, i: int) -> int:
    """Index of the bracket that closes text[i], or -1."""
    pairs = {"(": ")", "{": "}", "[": "]"}
    want = [pairs[text[i]]]
    j = i + 1
    while j < len(text):
        ch = text[j]
        if ch in pairs:
            want.append(pairs[ch])
        elif ch in ")}]":
            if not want or ch != want[-1]:
                return -1
            want.pop()
            if not want:
                return j
        j += 1
    return -1


IDENT = re.compile(r"[A-Za-z_]\w*")


def expand(line: str, macros: dict, depth: int = 0) -> str:
    if depth > 8 or not macros:
        return line
    out, i, changed = [], 0, False
    while i < len(line):
        m = IDENT.match(line, i)
        if not m or (i and (line[i - 1].isalnum() or line[i - 1] == "_")):
            out.append(line[i])
            i += 1
            continue
        name = m.group(0)
        j = m.end()
        if name in macros:
            params, body = macros[name]
            if params is None:
                out.append(body)
                i = j
                changed = True
                continue
            k = j
            while k < len(line) and line[k] in " \t":
                k += 1
            if k < len(line) and line[k] == "(":
                e = match_paren(line, k)
                if e > 0:
                    args = split_args(line[k + 1:e])
                    out.append(substitute(params, body, args))
                    i = e + 1
                    changed = True
                    continue
        out.append(name)
        i = j
    text = "".join(out)
    return expand(text, macros, depth + 1) if changed else text


def substitute(params: list[str], body: str, args: list[str]) -> str:
    values = dict(zip(params, args + [""] * (len(params) - len(args))))
    body = re.sub(r"#\s*(\w+)", lambda m: '"' + values.get(m.group(1), m.group(1)) + '"'
                  if m.group(1) in values else m.group(0), body.replace("##", "\x00"))
    body = re.sub(r"\b\w+\b", lambda m: values.get(m.group(0), m.group(0)), body)
    return re.sub(r"\s*\x00\s*", "", body)


class Source:
    """One source file, cleaned and preprocessed, with line numbers kept."""

    def __init__(self, path: Path, text: str | None = None):
        self.path = path
        self.rel = path.relative_to(REPO).as_posix() if text is None else path.as_posix()
        raw = path.read_text(encoding="utf-8", errors="replace") if text is None else text
        self.text = preprocess(clean(raw))
        self._starts = [0] + [m.end() for m in re.finditer("\n", self.text)]

    def line(self, pos: int) -> int:
        lo, hi = 0, len(self._starts) - 1
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if self._starts[mid] <= pos:
                lo = mid
            else:
                hi = mid - 1
        return lo + 1


class Function:
    def __init__(self, name, src: Source, pos, ret, body, params):
        self.name, self.src, self.pos, self.ret, self.body, self.params = name, src, pos, ret, body, params

    @property
    def where(self) -> str:
        return f"{self.src.rel}:{self.src.line(self.pos)}"


NOT_RET = {"return", "else", "new", "delete", "case", "throw", "co_return", "goto"}


def find_functions(src: Source) -> dict[str, list[Function]]:
    """Every function definition: a name, a parameter list, qualifiers, then a body."""
    found: dict[str, list[Function]] = {}
    text = src.text
    for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\(", text):
        name = m.group(1)
        if name in KEYWORDS or name in NOT_RET:
            continue
        before = text[:m.start()].rstrip()
        if not before or before[-1] in "=(,.!&|?:+-/%^~<[" and not before.endswith("::"):
            if not before.endswith("*") and not before.endswith("&") and not before.endswith(">"):
                continue
        if before.endswith("->") or (before.endswith(".") and not before.endswith("..")):
            continue
        prev = re.search(r"([A-Za-z_]\w*)\s*$", before)
        if prev and prev.group(1) in NOT_RET:
            continue
        if not prev and not before.endswith(("*", "&", ">", "::")):
            continue
        open_ = m.end() - 1
        close = match_paren(text, open_)
        if close < 0:
            continue
        k = close + 1
        tail = re.match(r"(\s*(noexcept(\s*\([^)]*\))?|const|override|final|throw\s*\(\s*\)|->\s*[\w:<>*&\s]+?))*\s*\{",
                        text[k:])
        if not tail:
            continue
        b = k + tail.end() - 1
        e = match_paren(text, b)
        if e < 0:
            continue
        start = max(text.rfind(";", 0, m.start()), text.rfind("}", 0, m.start()), text.rfind("{", 0, m.start()))
        ret = " ".join(text[start + 1:m.start()].split())
        ret = re.sub(r"\btemplate\s*<.*?>\s*", "", ret)
        if re.search(r"\b(if|while|for|switch|return)\b", ret) or "=" in ret:
            continue
        found.setdefault(name, []).append(Function(name, src, m.start(), ret, text[b + 1:e], text[open_ + 1:close]))
    return found


# ---- the verdict ---------------------------------------------------------------------------------------------------

def statements(body: str) -> list[str]:
    """Split a body into statements at top-level ';', '{' and '}'. Parentheses keep lambdas inside a call."""
    out, depth, cur = [], 0, []
    for ch in body:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if depth == 0 and ch in ";{}":
            s = "".join(cur).strip()
            if s:
                out.append(s)
            cur = []
        else:
            cur.append(ch)
    s = "".join(cur).strip()
    if s:
        out.append(s)
    return out


HEADER = re.compile(r"^\s*(?:else\b|do\b|try\b|__try\b|default\s*:|case\b[^:]*:(?!:)|"
                    r"(?:if|while|for|switch|__except|catch)\s*(?=\())")


def strip_headers(stmt: str) -> tuple[str, list[str]]:
    """Remove leading control headers and return the core statement and the header conditions."""
    conds = []
    while True:
        m = HEADER.match(stmt)
        if not m:
            break
        rest = stmt[m.end():]
        if rest.lstrip().startswith("(") and m.group(0).strip()[:2] in ("if", "wh", "fo", "sw", "__", "ca"):
            k = len(rest) - len(rest.lstrip())
            e = match_paren(rest, k)
            if e < 0:
                break
            conds.append(rest[k + 1:e])
            stmt = rest[e + 1:]
        else:
            stmt = rest
    return stmt.strip(), conds


CALL = re.compile(r"(?<![\w.])((?:[A-Za-z_]\w*\s*(?:::|\.|->)\s*)*)([A-Za-z_]\w*)\s*(?:<[^<>;()]*>)?\s*\(")


def calls_in(text: str) -> list[str]:
    return [m.group(2) for m in CALL.finditer(text) if m.group(2) not in KEYWORDS]


def top_level_assign(stmt: str) -> tuple[str, str] | None:
    depth = 0
    for i, ch in enumerate(stmt):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "=" and depth == 0:
            if stmt[i + 1:i + 2] == "=" or stmt[i - 1:i] in ("=", "!", "<", ">"):
                continue
            lhs = stmt[:i]
            if lhs and lhs[-1] in "+-*/|&^%<>":
                lhs = lhs[:-1]
            return lhs.strip(), stmt[i + 1:].strip()
    return None


def is_declaration(lhs: str) -> bool:
    return bool(re.match(r"^(?:const\s+|static\s+|volatile\s+|auto\s*)*[\w:<>,\s]*?[\w>]\s*[\s*&]+\s*\w+(\[\w*\])?$",
                         lhs)) and not re.search(r"->|\.", lhs) and not lhs.startswith("*")


def is_write(lhs: str) -> bool:
    if is_declaration(lhs):
        return False
    return bool(re.search(r"->|\.|\[|^\s*\*|^\s*\(\s*\*", lhs))


FAILURE_NAME = re.compile(r"^(STATUS_(?!SUCCESS$|PENDING$|MORE_PROCESSING_REQUIRED$)\w+|E_\w+|DXGI_ERROR_\w+|"
                          r"D3DDDIERR_\w+)$")


def ternary(expr: str) -> tuple[str, str] | None:
    """The two results of a top-level 'cond ? a : b', or None."""
    depth, q = 0, -1
    for i, ch in enumerate(expr):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif depth == 0 and ch == "?" and q < 0:
            q = i
        elif depth == 0 and ch == ":" and q >= 0 and expr[i - 1:i + 1] != "::" and expr[i:i + 2] != "::":
            return expr[q + 1:i].strip(), expr[i + 1:].strip()
    return None


def is_failure(expr: str) -> bool:
    """True when the expression names failure constants and nothing else. For a ternary, both results."""
    expr = expr.strip()
    while expr.startswith("(") and match_paren(expr, 0) == len(expr) - 1:
        expr = expr[1:-1].strip()
    t = ternary(expr)
    if t:
        return is_failure(t[0]) and is_failure(t[1])
    words = re.findall(r"[A-Za-z_]\w*", expr)
    rest = re.sub(r"[\s(),]|[A-Za-z_]\w*", "", expr)
    return bool(words) and not rest and all(w in REFUSAL or FAILURE_NAME.match(w) for w in words)


def fn_kind(fn: "Function") -> str:
    ret = fn.ret
    return ("void" if re.search(r"\b(void|VOID)\b", ret) and "*" not in ret else
            "status" if re.search(r"\b(HRESULT|NTSTATUS)\b", ret) else "value")


class Judge:
    def __init__(self, index: dict[str, list[Function]]):
        self.index = index
        self._work: dict[str, bool] = {}

    def resolve(self, name: str, near: Source | None = None) -> tuple[Function | None, bool]:
        defs = self.index.get(name, [])
        if not defs:
            return None, False
        if near:
            same = [d for d in defs if d.src is near]
            if same:
                return same[0], len(same) > 1 and len({d.body for d in same}) > 1
        return defs[0], len({(d.src.rel, d.body) for d in defs}) > 1

    def analyze(self, fn: Function) -> dict:
        work_calls, writes, refusals, returns, calls = [], 0, 0, [], []
        for raw in statements(fn.body):
            core, conds = strip_headers(raw)
            for c in conds:
                work_calls += [x for x in self.note(calls_in(c), calls) if self.call_is_work(x, fn.src)]
                a = top_level_assign(c)
                if a and is_write(a[0]):
                    writes += 1
            if not core:
                continue
            if re.search(r"\b(new|delete)\b|(->|\.)\s*~\w", core):
                writes += 1         # an object is built or destroyed
            if re.match(r"^return\b", core):
                expr = core[6:].strip()
                returns.append(expr)
                work_calls += [x for x in self.note(calls_in(expr), calls) if self.call_is_work(x, fn.src)]
                continue
            if any(re.search(r"\b" + r + r"\b", core) for r in REFUSAL_MARKERS):
                refusals += 1
                continue
            first = CALL.match(core)
            if first and first.start() == 0 and first.group(2) in NEUTRAL and not top_level_assign(core):
                continue
            if re.match(r"^\(void\)\s*", core):
                core = re.sub(r"^\(void\)\s*", "", core)
                first = CALL.match(core)
                if first and first.group(2) in NEUTRAL:
                    continue
            a = top_level_assign(core)
            if a:
                lhs, rhs = a
                if is_write(lhs) and not ZERO_VALUE.match(rhs):
                    writes += 1
                work_calls += [x for x in self.note(calls_in(rhs), calls) if self.call_is_work(x, fn.src)]
                if is_declaration(lhs) and "(" in lhs:
                    work_calls += [x for x in self.note(calls_in(lhs), calls) if self.call_is_work(x, fn.src)]
                continue
            work_calls += [x for x in self.note(calls_in(core), calls) if self.call_is_work(x, fn.src)]
        return {"work_calls": work_calls, "writes": writes, "refusals": refusals, "returns": returns,
                "calls": sorted(set(calls))}

    def note(self, names: list[str], into: list[str]) -> list[str]:
        into += [n for n in names if n not in NEUTRAL]
        return names

    def call_is_work(self, name: str, near: Source) -> bool:
        if name in NEUTRAL or name in KEYWORDS:
            return False
        if name in self._work:
            return self._work[name]
        fn, _ = self.resolve(name, near)
        if fn is None:
            return True
        self._work[name] = True        # recursion guard: a cycle counts as work
        a = self.analyze(fn)
        result = bool(a["work_calls"] or a["writes"])
        self._work[name] = result
        return result

    def verdict(self, name: str, near: Source, depth: int = 0) -> dict:
        fn, ambiguous = self.resolve(name, near)
        if fn is None:
            return {"function": name, "done": False, "reason": "no definition in the driver source", "source": None}
        a = self.analyze(fn)
        kind = fn_kind(fn)
        base = {"function": name, "source": fn.where}
        if ambiguous:
            base["ambiguous"] = True
        exprs = [r for r in a["returns"] if r]
        if exprs and all(self.fails(r, fn.src) for r in exprs) and kind != "void":
            return {**base, "done": False, "reason": "every return is a failure constant"}
        if kind == "value":
            if exprs and all(REFUSAL_VALUE.search(r) and not calls_in(r) for r in exprs):
                return {**base, "done": False, "reason": "every return is a 'not supported' answer"}
            return {**base, "done": True, "reason": "returns the answer",
                    **({"partial": True} if a["refusals"] else {})}
        work = a["work_calls"]
        # A forwarder: its one call outside NEUTRAL goes to a function of the same driver, and it writes nothing.
        if not a["writes"] and depth < 4 and len(a["calls"]) == 1 and a["calls"][0] != name:
            inner, _ = self.resolve(a["calls"][0], fn.src)
            if inner is not None and fn_kind(inner) != "value":
                bound = self.constant_refusal(fn, inner)
                if bound:
                    return {**base, "done": False,
                            "reason": f"forwards to {inner.name} with {bound}"}
                v = self.verdict(a["calls"][0], fn.src, depth + 1)
                return {**base, "done": v["done"], "reason": f"forwards to {a['calls'][0]}: {v['reason']}",
                        **({"partial": True} if v.get("partial") else {})}
        if not work and not a["writes"]:
            why = "refuses every call" if a["refusals"] else "only logs, counts, reads or writes zeros"
            return {**base, "done": False, "reason": why}
        partial = a["refusals"] > 0 or any(m in r for r in exprs for m in REFUSAL_MARKERS)
        return {**base, "done": True, "reason": "does work", **({"partial": True} if partial else {})}

    @staticmethod
    def param_names(fn: Function) -> list[str]:
        names = []
        for p in split_args(fn.params):
            p = p.split("=")[0].strip()
            m = re.search(r"(\w+)\s*(\[\w*\])?$", p)
            names.append(m.group(1) if m and p not in ("void", "") else "")
        return names

    def bindings(self, caller: Function, callee: Function, given: dict[str, str]) -> dict[str, str]:
        """Parameters of callee that a call in caller sets to a constant, or to a parameter already bound."""
        out = {}
        params = self.param_names(callee)
        for m in re.finditer(r"\b" + re.escape(callee.name) + r"\s*\(", caller.body):
            e = match_paren(caller.body, m.end() - 1)
            if e < 0:
                continue
            for k, arg in enumerate(split_args(caller.body[m.end():e])):
                if k >= len(params) or not params[k]:
                    continue
                if arg in given:
                    out[params[k]] = given[arg]
                elif re.fullmatch(r"\w+::\w+|[A-Z][A-Z0-9_]{2,}", arg):
                    out[params[k]] = arg
        return out

    def constant_refusal(self, caller: Function, callee: Function, given: dict | None = None, depth: int = 0) -> str:
        """A forwarder that passes a constant which a branch of the callee (or of a function it passes the value
        on to) answers with a refusal marker and a return: the constant, or ''."""
        bound = self.bindings(caller, callee, given or {})
        if not bound or depth > 3:
            return ""
        for param, const in bound.items():
            pat = (r"\bif\s*\(\s*" + re.escape(param) + r"\s*==\s*" + re.escape(const) + r"\s*\)\s*(\{[^{}]*\}|[^;]*;)")
            for m in re.finditer(pat, callee.body):
                block = m.group(1)
                if re.search(r"\breturn\b", block) and any(re.search(r"\b" + r + r"\b", block) for r in REFUSAL_MARKERS):
                    return f"{const}, which {callee.name} refuses"
        for name in set(calls_in(callee.body)):
            inner, _ = self.resolve(name, callee.src)
            if inner is not None and inner is not callee:
                found = self.constant_refusal(callee, inner, bound, depth + 1)
                if found:
                    return found
        return ""

    def fails(self, expr: str, near: Source, depth: int = 0) -> bool:
        """A return expression that can only be a failure: failure constants, or a call to a status function of
        the same driver whose every return fails."""
        expr = expr.strip()
        while expr.startswith("(") and match_paren(expr, 0) == len(expr) - 1:
            expr = expr[1:-1].strip()
        t = ternary(expr)
        if t:
            return self.fails(t[0], near, depth) and self.fails(t[1], near, depth)
        if is_failure(expr):
            return True
        m = re.match(r"^(?:\w+\s*(?:::|\.|->)\s*)*(\w+)\s*\(", expr)
        if not m or depth > 3 or match_paren(expr, m.end() - 1) != len(expr) - 1:
            return False
        fn, _ = self.resolve(m.group(1), near)
        if fn is None or fn_kind(fn) != "status":
            return False
        rets = [r for r in self.analyze(fn)["returns"] if r]
        return bool(rets) and all(self.fails(r, fn.src, depth + 1) for r in rets)


def load_sources(dirs: list[Path], exclude: re.Pattern) -> tuple[list[Source], dict[str, list[Function]]]:
    sources, index = [], {}
    for d in dirs:
        for p in sorted(d.iterdir()):
            if p.suffix in (".c", ".cpp", ".h") and not exclude.search(p.name):
                s = Source(p)
                sources.append(s)
                for k, v in find_functions(s).items():
                    index.setdefault(k, []).extend(v)
    return sources, index


def body_of(index, name: str, rel: str) -> Function:
    for f in index.get(name, []):
        if f.src.rel == rel:
            return f
    raise SystemExit(f"status_map: {name} not found in {rel}; the source layout changed, update this script")



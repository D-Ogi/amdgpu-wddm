def version_label(name: str) -> str:
    """WDDM2_9 -> WDDM 2.9, WIN8 -> WIN8."""
    m = re.fullmatch(r"WDDM(\d+(?:_\d+)*)", name)
    return f"WDDM {m.group(1).replace('_', '.')}" if m else name


def kmd_family(name: str) -> str:
    short = name.replace("DxgkDdi", "", 1)
    for family, pattern in KMD_FAMILIES:
        if re.search(pattern, short):
            return family
    return KMD_FAMILIES[-1][0]


def kmd_metric(kits: Path | None, prior: dict | None) -> dict:
    if kits:
        header = find_header(kits, KMD_HEADER)
        members = struct_members(header.read_text(encoding="utf-8", errors="replace"), "DRIVER_INITIALIZATION_DATA")
        slots = [{"name": m["name"], "since": m["since"]} for m in members if m["name"].startswith("DxgkDdi")
                 and is_slot(m)]
        taken = {s["name"] for s in slots}
        reserved = [m["name"] for m in members if m["name"] != "Version" and m["name"] not in taken]
        header_info = {"wdk": WDK_VERSION, "file": KMD_HEADER, "sha256": sha256(header),
                       "struct": "DRIVER_INITIALIZATION_DATA"}
        vheader = find_header(kits, VERSION_HEADER)
        versions = {k: int(v, 16) for k, v in re.findall(
            r"#define\s+DXGKDDI_INTERFACE_VERSION_(\w+)\s+0x([0-9A-Fa-f]+)", vheader.read_text(encoding="utf-8",
                                                                                           errors="replace"))}
        version_info = {"file": VERSION_HEADER, "sha256": sha256(vheader), "values": versions}
    else:
        slots = [{"name": s["name"], "since": s.get("since")} for g in prior["groups"] for s in g["slots"]]
        reserved = prior["reserved"]
        header_info = prior["header"]
        version_info = prior["interface_versions"]
    kmd = REPO / "driver" / "kmd"
    sources, index = load_sources([kmd], re.compile(r"(^test_|_test\.|probe)"))
    build = body_of(index, "WddmBuildTable", "driver/kmd/wddm.c")
    assigned = dict(re.findall(r"\bData\s*->\s*(DxgkDdi\w+)\s*=\s*([A-Za-z_]\w*)\s*;", build.body))
    judge = Judge(index)
    declared = re.search(r"Data->Version\s*=\s*DXGKDDI_INTERFACE_VERSION_(\w+)", build.body).group(1)
    values = version_info["values"]
    missing = sorted({s["since"] for s in slots if s["since"]} - set(values)) + ([declared] if declared not in values
                                                                                else [])
    if missing:
        raise SystemExit(f"status_map: no value for interface versions {missing} in {VERSION_HEADER}")
    names = {s["name"] for s in slots}
    unknown = sorted(set(assigned) - names)
    if unknown:
        raise SystemExit(f"status_map: WddmBuildTable sets members the header lacks: {unknown}")
    groups: dict[str, list] = {}
    for s in slots:
        entry = {"name": s["name"], "since": s["since"],
                 "targeted": s["since"] is None or values[s["since"]] <= values[declared]}
        if s["name"] in assigned:
            entry.update(judge.verdict(assigned[s["name"]], build.src))
        else:
            entry.update({"function": None, "done": False, "reason": "NULL in WddmBuildTable", "source": None})
        groups.setdefault(kmd_family(s["name"]), []).append(entry)
    return {
        "id": "kmd-ddi",
        "title": "Kernel-mode DDI",
        "header": header_info,
        "table": "WddmBuildTable in driver/kmd/wddm.c (the full WDDM table)",
        "declared_version": "DXGKDDI_INTERFACE_VERSION_" + declared,
        "declared_label": version_label(declared),
        "interface_versions": version_info,
        "reserved": reserved,
        "groups": [{"name": k, "slots": v} for k, v in groups.items()],
    }



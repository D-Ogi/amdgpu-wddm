def umd_metric(kits: Path | None, prior: dict | None) -> dict:
    d12 = REPO / "driver" / "umd" / "d3d12"
    sources, index = load_sources([d12, d12 / "engine-ddi"], re.compile(r"(-test\.cpp$|-probe\.cpp$|^harness)"))
    judge = Judge(index)
    fill = body_of(index, "fill_native_tables", "driver/umd/d3d12/native-tables.cpp")
    adapter_src = next(s for s in sources if s.rel.endswith("/adapter.cpp"))
    build = re.search(r"D3D12DDI_SUPPORTED_(\d{4})", adapter_src.text).group(1)
    case_type = {}
    for m in re.finditer(r"case\s+(D3D12DDI_TABLE_TYPE_\w+)\s*:\s*\{(.*?)(?=case\s+D3D12DDI_TABLE_TYPE_|default\s*:)",
                         fill.body, re.S):
        t = re.search(r"\b(?:using\s+\w+\s*=\s*)?(D3D12DDI_\w+_FUNCS_\w+)\b", m.group(2))
        case_type[m.group(1)] = t.group(1) if t else None
    aliases = dict(re.findall(r"using\s+(\w+)\s*=\s*(D3D12DDI_\w+)\s*;", fill.src.text))
    for k, v in case_type.items():
        if v is None:
            body = re.search(r"case\s+" + k + r"\s*:\s*\{(.*?)\n\s*\}", fill.body, re.S).group(1)
            alias = re.search(r"sizeof\((\w+)\)", body).group(1)
            case_type[k] = aliases[alias]
    adapter_struct = "D3D12DDI_ADAPTERFUNCS"
    tables = [("Adapter", adapter_struct, None)] + [
        (label, case_type[t], t) for label, t in (
            ("Device core", "D3D12DDI_TABLE_TYPE_DEVICE_CORE"),
            ("Command list", "D3D12DDI_TABLE_TYPE_COMMAND_LIST_3D"),
            ("Command queue", "D3D12DDI_TABLE_TYPE_COMMAND_QUEUE_3D"),
            ("Extended features", "D3D12DDI_TABLE_TYPE_0020_EXTENDED_FEATURES"))]
    missing = sorted(set(case_type) - {t for _, _, t in tables})
    if missing:
        raise SystemExit(f"status_map: fill_native_tables publishes tables this script does not count: {missing}")
    if kits:
        header = find_header(kits, UMD_HEADER)
        htext = header.read_text(encoding="utf-8", errors="replace")
        layouts = {s: struct_members(htext, s) for _, s, _ in tables}
        header_info = {"wdk": WDK_VERSION, "file": UMD_HEADER, "sha256": sha256(header)}
    else:
        layouts = {g["struct"]: g["layout"] for g in prior["groups"]}
        header_info = prior["header"]

    # Assignments, in the order the driver makes them. Each list is (member, function, source Function).
    def scan(fn: Function, table_var: str, seen=None) -> list[tuple[str, str, Function]]:
        seen = seen or set()
        out = []
        pat = re.compile(r"(?:\b" + table_var + r"\s*(?:->|\.)|\(\s*" + table_var + r"\s*\)\s*->)\s*(pfn\w+)\s*=\s*"
                         r"([^;]+);|\b([a-z_]\w*)\s*\(\s*&?\s*" + table_var + r"\b")
        for m in pat.finditer(fn.body):
            if m.group(1):
                out.append((m.group(1), m.group(2).strip(), fn))
            else:
                callee = m.group(3)
                if callee in seen or callee in KEYWORDS:
                    continue
                inner, _ = judge.resolve(callee, fn.src)
                if inner is None or "pfn" not in inner.body:
                    continue
                params = [p.strip() for p in split_args(inner.params) if p.strip()]
                pname = re.search(r"(\w+)\s*$", params[0]).group(1) if params else table_var
                out += scan(inner, pname, seen | {callee})
        return out

    def rhs_function(rhs: str) -> str:
        if rhs.startswith("FailSafe<") or "FailSafe<" in rhs.split("?")[-1]:
            return "FailSafe"
        m = re.match(r"&?\s*([A-Za-z_][\w:]*)\s*$", rhs)
        return m.group(1).split("::")[-1] if m else rhs

    def judge_slot(func: str, src: Function, wrapped: dict | None = None) -> dict:
        if func == "FailSafe":
            return {"function": "FailSafe", "done": False, "reason": "fail-safe entry of engine-ddi",
                    "source": src.where}
        v = judge.verdict(func, src.src)
        if wrapped is not None and not wrapped["done"]:
            return {**v, "done": False, "reason": f"wraps {wrapped['function']}: {wrapped['reason']}"}
        return v

    groups = []
    # The adapter table: the aggregate that OpenAdapter12 stores.
    open_adapter = body_of(index, "OpenAdapter12", "driver/umd/d3d12/adapter.cpp")
    agg = re.search(r"\*\s*a\s*->\s*pAdapterFuncs\s*=\s*\{([^{}]+)\}", open_adapter.body).group(1)
    per_table: dict[str, dict[str, tuple[str, Function]]] = {"Adapter": {}}
    slots_adapter = [m for m in layouts[adapter_struct] if is_slot(m)]
    for member, func in zip(layouts[adapter_struct], [x.strip() for x in split_args(agg)]):
        per_table["Adapter"][member["name"]] = (func, open_adapter)
    # Device core: engine fill (fail-safe, then the engine modules), the shell's slots, then the wrapped resources.
    core_case = re.search(r"case\s+D3D12DDI_TABLE_TYPE_DEVICE_CORE\s*:\s*\{(.*?)\n\s{4}\}", fill.body, re.S).group(1)
    engine_core = body_of(index, "fill_device_core", "driver/umd/d3d12/engine-ddi/context.cpp")
    core: dict[str, tuple[str, Function]] = {}
    for member, rhs, f in scan(engine_core, "table"):
        core[member] = (rhs_function(rhs), f)
    shell_fn = Function("fill_native_tables", fill.src, fill.pos, "", core_case.split("compose_core_0092")[0], "")
    for member, rhs, f in scan(shell_fn, "shell"):
        core[member] = (rhs_function(rhs), f if f is not shell_fn else fill)
    wraps = {}
    for m in re.finditer(r"\boriginal\.(pfn\w+)\s*=\s*(\w+)\s*;", core_case):
        if re.search(r"store\(\s*original\." + m.group(1) + r"\s*\)", core_case):
            wraps[m.group(1)] = core.get(m.group(1))
        core[m.group(1)] = (m.group(2), fill)
    per_table["Device core"] = core
    # Command list: the engine fill for table 1 (graphics), then the shell's Present.
    engine_list = body_of(index, "fill_command_list", "driver/umd/d3d12/engine-ddi/context.cpp")
    lst = {}
    for member, rhs, f in scan(engine_list, "table"):
        lst[member] = (rhs_function(rhs), f)
    compose = body_of(index, "compose_list_0092", "driver/umd/d3d12/device-table.h")
    present_arg = re.search(r"compose_list_0092\s*\(([^;]*)\)\s*;", fill.body)
    lst["pfnPresent"] = (split_args(present_arg.group(1))[3].strip(), fill)
    assert "candidate.pfnPresent = present" in " ".join(compose.body.split())
    per_table["Command list"] = lst
    # Command queue and extended features: the shell's fill functions behind the wrapping thunks.
    queue_fill = body_of(index, "fill_native_queue_table", "driver/umd/d3d12/native-queue-ddi.cpp")
    per_table["Command queue"] = {m: (rhs_function(r), f) for m, r, f in scan(queue_fill, "candidate")}
    ext_fill = body_of(index, "fill_native_extended_table", "driver/umd/d3d12/native-queue-ddi.cpp")
    ext_agg = re.search(r"\*\s*output\s*=\s*\{([^{}]+)\}", ext_fill.body).group(1)
    per_table["Extended features"] = {}
    ext_struct = case_type["D3D12DDI_TABLE_TYPE_0020_EXTENDED_FEATURES"]
    for member, func in zip(layouts[ext_struct], [x.strip() for x in split_args(ext_agg)]):
        per_table["Extended features"][member["name"]] = (func, ext_fill)

    for label, struct, _ in tables:
        layout = layouts[struct]
        assigned = per_table[label]
        unknown = sorted(set(assigned) - {m["name"] for m in layout})
        if unknown:
            raise SystemExit(f"status_map: the {label} table sets members that {struct} lacks: {unknown}")
        entries = []
        for m in layout:
            if not is_slot(m):
                continue
            if m["name"] in assigned:
                func, src = assigned[m["name"]]
                wrapped = None
                if label == "Device core" and m["name"] in wraps and wraps[m["name"]]:
                    wf, ws = wraps[m["name"]]
                    wrapped = judge_slot(wf, ws)
                entry = {"name": m["name"], **judge_slot(func, src, wrapped)}
            else:
                entry = {"name": m["name"], "function": None, "done": False, "reason": "NULL", "source": None}
            entries.append(entry)
        groups.append({"name": label, "struct": struct, "layout": layout, "slots": entries})
    return {
        "id": "d3d12-ddi",
        "title": "D3D12 user-mode DDI",
        "header": header_info,
        "build": build,
        "table": "OpenAdapter12 and fill_native_tables in driver/umd/d3d12 (the command-list slots of table 1, "
                 "the graphics table)",
        "groups": groups,
    }



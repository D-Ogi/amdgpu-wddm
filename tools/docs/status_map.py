def find_header(kits: Path, rel: str) -> Path:
    hits = sorted(kits.rglob(f"Include/{WDK_VERSION}/{rel}"))
    if not hits:
        raise SystemExit(f"status_map: {rel} of WDK {WDK_VERSION} not found under the --kits directory")
    return hits[0]


def struct_members(text: str, name: str) -> list[dict]:
    """Members of 'typedef struct NAME { ... }' in order, each with its type and the interface-version guard."""
    m = re.search(r"typedef\s+struct\s+_?" + re.escape(name) + r"\b[^{;]*\{", text)
    if not m:
        raise SystemExit(f"status_map: struct {name} not found in the WDK header")
    e = match_paren(text, m.end() - 1)
    members, guards = [], []
    for line in text[m.end():e].split("\n"):
        s = line.strip()
        g = re.match(r"#\s*if\s*\(?\s*DXGKDDI_INTERFACE_VERSION\s*>=\s*DXGKDDI_INTERFACE_VERSION_(\w+)", s)
        if g:
            guards.append(g.group(1))
            continue
        if s.startswith("#if"):
            guards.append(None)
            continue
        if s.startswith("#endif"):
            if guards:
                guards.pop()
            continue
        mm = re.match(r"^([A-Za-z_][\w\s*]*?)\s*\b([A-Za-z_]\w*)\s*;", s)
        if mm:
            typ = " ".join(mm.group(1).split())
            since = next((x for x in reversed(guards) if x), None)
            members.append({"name": mm.group(2), "type": typ, "since": since})
    return members


def is_slot(member: dict) -> bool:
    return not re.fullmatch(r"(PVOID|VOID\s*\*|void\s*\*|ULONG|UINT|SIZE_T)", member["type"].replace(" *", "*")
                            .replace("* ", "*").replace("VOID*", "VOID *").replace("void*", "void *"))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()



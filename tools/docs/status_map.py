def squarify(values: list[float], x: float, y: float, w: float, h: float) -> list[tuple[float, float, float, float]]:
    """Bruls, Huizing and van Wijk (2000). values sorted descending, positive. Returns one rectangle per value."""
    total = sum(values)
    scale = w * h / total
    areas = [v * scale for v in values]
    rects: list = []
    row: list[float] = []

    def worst(r, side):
        s = sum(r)
        return max(side * side * max(r) / (s * s), s * s / (side * side * min(r)))

    def lay(r):
        nonlocal x, y, w, h
        s = sum(r)
        if w >= h:
            cw = s / h
            yy = y
            for a in r:
                rects.append((x, yy, cw, a / cw))
                yy += a / cw
            x += cw
            w -= cw
        else:
            ch = s / w
            xx = x
            for a in r:
                rects.append((xx, y, a / ch, ch))
                xx += a / ch
            y += ch
            h -= ch

    i = 0
    while i < len(areas):
        side = min(w, h)
        a = areas[i]
        if not row or worst(row + [a], side) <= worst(row, side):
            row.append(a)
            i += 1
        else:
            lay(row)
            row = []
    if row:
        lay(row)
    return rects



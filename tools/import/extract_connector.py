"""Extract the AMD AUX power and HPD operations for DCN201 (MIT)."""
import argparse
from pathlib import Path
import re
import shutil
from extract_display import extract
from extract_hdmi_link import declaration

ROOT=Path(__file__).resolve().parents[2]
DC='drivers/gpu/drm/amd/display/dc/'
SOURCES={
    'dce_aux.c': DC+'dce/dce_aux.c',
    'irq.c': DC+'irq/irq_service.c',
    'link.c': DC+'dio/dcn10/dcn10_link_encoder.c',
    'dcn201_resource.c': DC+'resource/dcn201/dcn201_resource.c',
    'dp_training.c': DC+'link/protocols/link_dp_training.c',
    'dp_training_8b10b.c': DC+'link/protocols/link_dp_training_8b_10b.c',
    'dp_training_8b10b.h': DC+'link/protocols/link_dp_training_8b_10b.h',
    'dp_types.h': DC+'dc_dp_types.h',
    'link_service_types.h': 'drivers/gpu/drm/amd/display/include/link_service_types.h',
}


def functions(source, names):
    parts=[source[:source.index('*/')+2], '// Generated by extract_connector.py. Do not edit.']
    for name in names:
        m=re.findall(r'^(?:static )?(?:void|bool|uint32_t|enum \w+)\s+'+re.escape(name)+
                     r'\s*\([^;]*?\)\s*\n\{.*?^\}', source, re.M|re.S)
        if len(m)!=1: raise ValueError('function '+name)
        parts+=m
    return '\n\n'.join(parts)+'\n'


def generate(ref):
    aux=(ref/'dce_aux.c').read_text()
    start=aux.index('\tif (field == 0) {', aux.index('static bool acquire_engine('))
    end=aux.index('\n\t/* request SW to access AUX */',start)
    body=aux[start:end]
    if body.count('REG_WAIT')!=2 or body.count('REG_WRITE')!=2:
        raise ValueError('AUX enable sequence changed')
    types=(ref/'dp_types.h').read_text()
    layouts=[types[:types.index('*/')+2], '// Generated by extract_connector.py. Do not edit.']
    for name in ['dc_lane_count', 'dc_link_rate', 'dc_voltage_swing', 'dc_pre_emphasis',
                 'dc_dp_training_pattern', 'dp_link_encoding', 'link_training_result']:
        layouts.append(declaration(types,'enum',name))
    for name in ['lane_status', 'lane_align_status_updated', 'lane_adjust', 'dpcd_training_lane']:
        layouts.append(declaration(types,'union',name))
    panel=declaration((ref/'link_service_types.h').read_text(),'enum','dp_panel_mode')
    protocol=(ref/'drm_dp.h').read_text(encoding='utf-8')
    constants=[protocol[:protocol.index('*/')+2], '// Generated by extract_connector.py. Do not edit.']
    names=['DP_DPCD_REV','DP_DPCD_REV_10','DP_DPCD_REV_11','DP_DPCD_REV_12','DP_DPCD_REV_14',
           'DP_MAX_LINK_RATE','DP_MAX_LANE_COUNT','DP_MAX_LANE_COUNT_MASK','DP_ENHANCED_FRAME_CAP',
           'DP_TRAINING_AUX_RD_INTERVAL','DP_TRAINING_AUX_RD_MASK', 'DP_LINK_BW_SET',
           'DP_LANE_COUNT_SET','DP_LANE_COUNT_ENHANCED_FRAME_EN','DP_TRAINING_PATTERN_SET',
           'DP_TRAINING_LANE0_SET','DP_TRAINING_PATTERN_DISABLE','DP_TRAINING_PATTERN_1',
           'DP_TRAINING_PATTERN_2','DP_LINK_SCRAMBLING_DISABLE','DP_DOWNSPREAD_CTRL',
           'DP_MAIN_LINK_CHANNEL_CODING_SET','DP_SET_ANSI_8B10B', 'DP_LANE0_1_STATUS',
           'DP_SET_POWER','DP_SET_POWER_D0','DP_SET_POWER_D3',
           'DP_LANE_CR_DONE','DP_LANE_CHANNEL_EQ_DONE','DP_LANE_SYMBOL_LOCKED','DP_INTERLANE_ALIGN_DONE',
           'DP_TPS3_SUPPORTED','DP_MAX_DOWNSPREAD','DP_TPS4_SUPPORTED','DP_TRAINING_PATTERN_3',
           'DP_TRAINING_PATTERN_4','DP_LINK_BW_1_62','DP_LINK_BW_2_7','DP_LINK_BW_5_4','DP_LINK_BW_8_1',
           'DP_DOWNSTREAMPORT_PRESENT','DP_DWN_STRM_PORT_PRESENT','DP_DWN_STRM_PORT_TYPE_MASK',
           'DP_DWN_STRM_PORT_TYPE_DP','DP_DWN_STRM_PORT_TYPE_ANALOG','DP_DWN_STRM_PORT_TYPE_TMDS',
           'DP_DETAILED_CAP_INFO_AVAILABLE','DP_DOWN_STREAM_PORT_COUNT','DP_PORT_COUNT_MASK','DP_DOWNSTREAM_PORT_0',
           'DP_DS_PORT_TYPE_MASK','DP_DS_PORT_TYPE_DP','DP_DS_PORT_TYPE_VGA','DP_DS_PORT_TYPE_DVI',
           'DP_DS_PORT_TYPE_HDMI','DP_DS_PORT_TYPE_DP_DUALMODE']
    for name in names:
        m=re.findall(r'^#\s*define\s+'+name+r'\s+[^\n]+',protocol,re.M)
        if len(m)!=1: raise ValueError('DPCD constant '+name)
        constants+=m
    retry=(ref/'dp_training_8b10b.h').read_text()
    for name in ['LINK_TRAINING_MAX_CR_RETRY', 'LINK_TRAINING_MAX_RETRY_COUNT']:
        layouts+=re.findall(r'^#define '+name+r'\s+[^\n]+',retry,re.M)
    checks=functions((ref/'dp_training.c').read_text(), ['dp_translate_training_aux_read_interval',
        'dp_get_cr_failure', 'dp_is_max_vs_reached', 'dp_is_cr_done', 'dp_is_ch_eq_done',
        'dp_is_symbol_locked', 'dp_is_interlane_aligned'])
    loops=functions((ref/'dp_training_8b10b.c').read_text(), [
        'perform_8b_10b_clock_recovery_sequence','perform_8b_10b_channel_equalization_sequence'])
    return {
        'aux_enable.inc': aux[:aux.index('*/')+2]+'\n// Generated by extract_connector.py: acquire_engine power branch.\n'+body+'\n',
        'hpd_ack.inc': extract((ref/'irq.c').read_text(),['hpd0_ack']),
        'dp_training_types.inc':'\n\n'.join(layouts)+'\n',
        'dp_training_checks.inc':checks,
        'dp_training_loops.inc':loops,
        'dpcd_constants.inc':'\n\n'.join(constants)+'\n',
        'dp_phy_pattern.inc':panel+'\n'+functions((ref/'link.c').read_text(),[
            'enable_phy_bypass_mode','disable_prbs_mode','set_link_training_complete',
            'dcn10_link_encoder_set_dp_phy_pattern_training_pattern','setup_panel_mode',
            'set_dp_phy_pattern_passthrough_mode','enc1_configure_encoder','link_encoder_disable']),
    }


def main():
    ap=argparse.ArgumentParser(__doc__)
    ap.add_argument('--import-linux',type=Path)
    ap.add_argument('--check',action='store_true')
    args=ap.parse_args()
    if args.check and args.import_linux: ap.error('check cannot import')
    ref=ROOT/'driver/amdgpu-import/reference/connector'
    if args.import_linux:
        ref.mkdir(exist_ok=True)
        for name,path in SOURCES.items(): shutil.copyfile(args.import_linux/path,ref/name)
    for name,content in generate(ref).items():
        out=ROOT/'driver/shim'/name
        if args.check:
            if out.read_text()!=content: raise SystemExit('stale '+name)
        else: out.write_text(content,newline='\n')
    print('connector extracts '+('checked' if args.check else 'written'))


if __name__=='__main__': main()

"""Extract DCN201's DP SST stream setup, blank and unblank (AMD, MIT)."""
import argparse
import json
from pathlib import Path
import re
import shutil
from extract_connector import functions
from extract_hdmi_link import declaration

ROOT=Path(__file__).resolve().parents[2]
SOURCES={
    'stream_encoder.h':'drivers/gpu/drm/amd/display/dc/inc/hw/stream_encoder.h',
    'stream10.h':'drivers/gpu/drm/amd/display/dc/dio/dcn10/dcn10_stream_encoder.h',
    'timing_generator.h':'drivers/gpu/drm/amd/display/dc/inc/hw/timing_generator.h',
}
def generate(ref):
    stream=(ROOT/'driver/amdgpu-import/reference/hdmi-link/stream.c').read_text()
    types=(ref/'stream_encoder.h').read_text()
    body=functions(stream,['enc1_stream_encoder_dp_set_stream_attribute',
        'enc1_stream_encoder_dp_blank','enc1_stream_encoder_dp_unblank'])
    header=(ref/'stream10.h').read_text()
    regs=sorted(set(re.findall(r'REG(?:_[A-Z0-9_]+)?\(\s*(\w+)',body)))
    fields=sorted(set(re.findall(r'SF\((\w+),\s*(\w+),\s*mask_sh\)',header)))
    aliases='// Generated by extract_dp_stream.py; AMD DCN201 stream aliases.\n'
    names=[]
    for reg in regs:
        matches=set(re.findall(r'SRI\('+reg+r',\s*(\w+),\s*id\)',header))
        if len(matches)!=1:raise ValueError(f'{reg}: {matches}')
        full=next(iter(matches))+'0_'+reg;names+=['mm'+full]
        aliases+=f'#define REG_{reg} BC250_REG_DMU_{full}\n'
        for source,field in fields:
            if source==full:aliases+=f'#define MASK_{reg}_{field} {source}__{field}_MASK\n'
    layouts=[types[:types.index('*/')+2],'// Generated by extract_dp_stream.py.']
    for name in ['dp_pixel_encoding_type','dp_component_depth']:
        layouts.append(declaration(types,'enum',name))
    layouts.append(declaration((ref/'timing_generator.h').read_text(),'enum','h_timing_div_mode'))
    service=(ref/'link_service_types.h').read_text()
    layouts.append(declaration(service,'enum','dpcd_source_sequence'))
    layouts.append(next(m.group(0) for m in re.finditer(r'enum\s*\{[^}]*\};',service,re.S)
                        if 'LINK_RATE_REF_FREQ_IN_KHZ' in m.group(0)))
    layouts+=re.findall(r'^#define DP_BLANK_MAX_RETRY\s+[^\n]+',stream,re.M)
    return {'dp_stream.inc':body,'dp_stream_layouts.inc':'\n\n'.join(layouts)+'\n',
            'dp_stream_registers.inc':aliases,'dp_stream_registers.json':json.dumps(names,indent=2)+'\n'}
def main():
    ap=argparse.ArgumentParser(__doc__);ap.add_argument('--import-linux',type=Path);ap.add_argument('--check',action='store_true');a=ap.parse_args()
    if a.check and a.import_linux:ap.error('check cannot import')
    ref=ROOT/'driver/amdgpu-import/reference/connector'
    if a.import_linux:
        for name,path in SOURCES.items():shutil.copyfile(a.import_linux/path,ref/name)
    for name,content in generate(ref).items():
        p=ROOT/'driver/shim'/name
        if a.check:
            if p.read_text()!=content:raise SystemExit('stale '+name)
        else:p.write_text(content,newline='\n')
    print('DP stream extracts '+('checked' if a.check else 'written'))
if __name__=='__main__':main()

"""Reproduce the original ATOM display command wire declarations (AMD, MIT)."""
import argparse
from pathlib import Path
import re
import shutil
from extract_hdmi_link import declaration

ROOT=Path(__file__).resolve().parents[2]

def main():
    ap=argparse.ArgumentParser(__doc__);ap.add_argument('--check',action='store_true');ap.add_argument('--import-linux',type=Path);a=ap.parse_args()
    if a.check and a.import_linux:ap.error('check cannot import')
    objects=ROOT/'driver/amdgpu-import/reference/connector/grph_object_id.h'
    if a.import_linux:
        shutil.copyfile(a.import_linux/'drivers/gpu/drm/amd/display/include/grph_object_id.h',objects)
    atom=(ROOT/'driver/amdgpu-import/reference/atom/atomfirmware.h').read_text()
    parts=[atom[:atom.index('*/')+2],'// Generated by extract_link_commands.py.','#pragma pack(push, 1)']
    for name in ['set_pixel_clock_parameter_v1_7','dig_encoder_stream_setup_parameters_v1_5',
                 'dig_transmitter_control_parameters_v1_6','dig_transmitter_control_ps_allocation_v1_6',
                 'atom_display_controller_info_v4_1','atom_display_controller_info_v4_2']:
        parts.append(declaration(atom,'struct',name))
    parts+=['#pragma pack(pop)']
    for name in ['atom_dig_encoder_control_action','atom_dig_transmitter_control_action','atom_encode_mode_def',
                 'atom_ppll_def','atom_set_pixel_clock_v1_7_misc_info','atom_panel_bit_per_color']:
        parts.append(declaration(atom,'enum',name))
    parts+=re.findall(r'^#define PANEL_8BIT_PER_COLOR\s+[^\n]+',atom,re.M)
    parts.append(declaration(objects.read_text(),'enum','connector_id'))
    out=ROOT/'driver/shim/link_command_layouts.inc';content='\n\n'.join(parts)+'\n'
    if a.check:
        if out.read_text()!=content: raise SystemExit('stale '+out.name)
    else: out.write_text(content,newline='\n')
    print('link command layouts '+('checked' if a.check else 'written'))

if __name__=='__main__':main()

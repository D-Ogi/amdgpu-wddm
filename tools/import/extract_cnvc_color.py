#!/usr/bin/env python3
"""Extract DCN201 CNVC setup and the DC input CSC tables for CPU preparation."""
import argparse
import hashlib
import re
from extract_scaler_geometry import ROOT, REF, COMMIT, extract

OUT = ROOT / 'driver/shim/generated/dc_cnvc_color.inc'


def generate():
    declarations = {
        'hdmi-link/dc_hw_types.h': ['enum surface_pixel_format', 'enum dc_color_space', 'struct dc_csc_transform'],
        'hw_shared.h': ['enum expansion_mode'],
        'dcn10_dpp.h': ['enum dcn10_input_csc_select'],
        'dpp.h': ['struct dpp_input_csc_matrix', 'struct cnv_alpha_2bit_lut'],
        'dcn201_dpp.c': [],
    }
    # Declarations precede the capture callback, and the original setup function
    # follows it. Both generated parts are included once in the same C unit.
    pieces = ['/* SPDX-License-Identifier: MIT */',
              '/* Generated by tools/import/extract_cnvc_color.py. Do not edit.\n'
              f' * PROVENANCE: Linux amdgpu DC, MIT, {COMMIT}.\n'
              ' * Declarations, matrix table and setup function are verbatim. */',
              '#ifndef BC250_CNVC_FUNCTION']
    function = None
    for name, decls in declarations.items():
        raw = (REF / name).read_bytes()
        text = raw.decode().replace('\r\n', '\n')
        pieces += [text[:text.index('*/') + 2],
                   f'/* {name}, sha256 {hashlib.sha256(raw).hexdigest()} */']
        for decl in decls:
            found = re.findall(r'^' + re.escape(decl) + r' \{.*?^\};', text, re.M | re.S)
            if len(found) != 1:
                raise ValueError(decl)
            pieces.append(found[0])
        if name == 'dpp.h':
            found = re.findall(r'^static const struct dpp_input_csc_matrix __maybe_unused dpp_input_csc_matrix\[\] = \{.*?^\};', text, re.M | re.S)
            if len(found) != 1:
                raise ValueError('CSC matrix table')
            pieces.append(found[0])
        if name == 'dcn201_dpp.c':
            function = extract(text, 'dpp201_cnv_setup')
    pieces += ['#else', function, '#endif']
    return ('\n\n'.join(pieces).rstrip() + '\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUT.read_bytes() != expected:
            raise SystemExit('CNVC color extraction mismatch')
    else:
        OUT.write_bytes(expected)
    print('CNVC color extraction OK')

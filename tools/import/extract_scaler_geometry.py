#!/usr/bin/env python3
"""Extract AMD's scaler viewport/phase function and its fixed-point dependencies."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / 'driver/amdgpu-import/reference'
OUT = ROOT / 'driver/shim/generated/dc_scaler_geometry.inc'
COMMIT = '7d0a66e4bb9081d75c82ec4957c50034cb0ea449'
FUNCTIONS = [
    ('fixed31_32.h', ['dc_fixpt_from_int', 'dc_fixpt_add', 'dc_fixpt_add_int',
                      'dc_fixpt_mul_int', 'dc_fixpt_div_int', 'dc_fixpt_floor',
                      'dc_fixpt_truncate']),
    ('fixpt31_32.c', ['complete_integer_division_u64', 'dc_fixpt_from_fraction',
                     'dc_fixpt_mul']),
    ('dc_resource.c', ['calculate_init_and_vp']),
]


def extract(text, name):
    # These pinned functions have an unindented declaration and closing brace.
    matches = list(re.finditer(r'^(?:static inline |static )?(?:struct fixed31_32|'
                              r'unsigned long long|int|void) ' + re.escape(name)
                              + r'\([^;]*?^\{\n.*?^\}', text, re.M | re.S))
    if len(matches) != 1:
        raise ValueError(f'Expected one definition of {name}, got {len(matches)}')
    return matches[0].group() + '\n'


def generate():
    pieces = ['/* SPDX-License-Identifier: MIT */\n'
              '/* Generated by tools/import/extract_scaler_geometry.py. Do not edit.\n'
              f' * PROVENANCE: Linux amdgpu DC, MIT, {COMMIT}.\n'
              ' * Functions are verbatim. Type declarations and platform services\n'
              ' * are in bc250_scaler_geometry.c. Source licenses are retained\n'
              ' * in driver/amdgpu-import/reference/. */\n']
    for filename, names in FUNCTIONS:
        raw = (REF / filename).read_bytes()
        text = raw.decode('utf-8')
        if filename == 'fixed31_32.h':
            pieces.append(text[:text.index('*/') + 2] + '\n')
        pieces.append(f'\n/* {filename}, sha256 {hashlib.sha256(raw).hexdigest()} */\n')
        pieces.extend(extract(text, name) for name in names)
    return '\n'.join(pieces).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUT.read_bytes() != generated:
            raise SystemExit('Scaler geometry extraction is stale')
    else:
        OUT.write_bytes(generated)
    print('Scaler geometry extraction OK')


if __name__ == '__main__':
    main()

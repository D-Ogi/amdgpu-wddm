"""Import the MIT AMD ATOM input layouts; keep original sources and reproducible extracts."""
import argparse
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {
    'atom.c': 'drivers/gpu/drm/amd/amdgpu/atom.c',
    'atom.h': 'drivers/gpu/drm/amd/amdgpu/atom.h',
    'atomfirmware.h': 'drivers/gpu/drm/amd/include/atomfirmware.h',
    'command_table2.c': 'drivers/gpu/drm/amd/display/dc/bios/command_table2.c',
}


def layouts(source):
    parts = [source[:source.index('*/')+2], '// Generated by tools/import/extract_atom.py. Do not edit.']
    for name in ('amd_acpi_description_header', 'uefi_acpi_vfct', 'vfct_image_header',
                 'atom_common_table_header', 'atom_master_list_of_command_functions_v2_1',
                 'atom_master_list_of_data_tables_v2_1'):
        match = re.search(r'^struct\s+'+name+r'\s*\{.*?^\};', source, re.M | re.S)
        if not match:
            raise ValueError('missing struct '+name)
        parts.append(match.group())
    return '\n\n'.join(parts)+'\n'


def opcodes(source):
    body = source.split('} opcode_table[ATOM_OP_CNT] = {', 1)[1].split('\n};', 1)[0]
    ops = [('invalid', '0')] + re.findall(r'atom_op_(\w+),\s*(\w+)', body)
    if len(ops) != 127:
        raise ValueError('ATOM opcode count changed')
    names = list(dict.fromkeys(name for name, _ in ops))
    args = dict(ATOM_ARG_REG=0, ATOM_ARG_PS=1, ATOM_ARG_WS=2, ATOM_ARG_FB=3, ATOM_ARG_PLL=6, ATOM_ARG_MC=7,
                ATOM_PORT_ATI=0, ATOM_PORT_PCI=1, ATOM_PORT_SYSIO=2,
                ATOM_COND_ABOVE=0, ATOM_COND_ABOVEOREQUAL=1, ATOM_COND_ALWAYS=2, ATOM_COND_BELOW=3,
                ATOM_COND_BELOWOREQUAL=4, ATOM_COND_EQUAL=5, ATOM_COND_NOTEQUAL=6,
                ATOM_UNIT_MICROSEC=0, ATOM_UNIT_MILLISEC=1)
    parts = [source[:source.index('*/')+2], '// Generated from the original atom.c opcode_table; do not edit.',
             'enum atom_checked_op { '+', '.join('AtomOp_'+n for n in names)+' };',
             'static const struct { unsigned char op, arg; } AtomOpcode[127] = {']
    parts += ['    { AtomOp_'+name+', '+str(args[arg] if arg != '0' else 0)+' },' for name,arg in ops]
    parts.append('};')
    return '\n'.join(parts)+'\n'


def interpreter(source):
    arrays=source[source.index('static uint32_t atom_arg_mask'):source.index('static int debug_depth;')]
    core=source[source.index('static uint32_t atom_get_src_int'):source.index('static int amdgpu_atom_execute_table_locked(struct atom_context *ctx, int index, uint32_t *params, int params_size)\n{')]
    # Each deviation is a checked boundary, not a reimplementation of ATOM arithmetic.
    changes=[
        ('1 << gctx->shift', 'UINT32_C(1) << gctx->shift', 2),
        ('gctx->shift = val;', 'if (val >= 32) { atom_fail(gctx, BC250_ATOM_PARAMETER); return; }\n\t\t\tgctx->shift = (uint8_t)val;', 1),
        ('shift = atom_get_src(ctx, attr, ptr);', 'shift = atom_shift(ctx->ctx, atom_get_src(ctx, attr, ptr));', 2),
        ('shift = atom_get_src_direct(ctx, ATOM_SRC_BYTE0, ptr);',
         'shift = atom_shift(ctx->ctx, atom_get_src_direct(ctx, ATOM_SRC_BYTE0, ptr));', 2),
        ('if (idx == 0)\n', 'if (idx == 0 && val > UINT32_MAX / 4u) { atom_fail(gctx, BC250_ATOM_IO); return; }\n\t\t\tif (idx == 0)\n', 1),
    ]
    for old,new,count in changes:
        if not count:
            continue
        if core.count(old)!=count:
            raise ValueError('ATOM guard anchor changed: '+old)
        core=core.replace(old,new)
    anchor='\tstruct atom_context *gctx = ctx->ctx;\n\told_val &= '
    if core.count(anchor)!=1:
        raise ValueError('ATOM write guard anchor changed')
    core=core.replace(anchor,'\tstruct atom_context *gctx = ctx->ctx;\n\tif (gctx->status != BC250_ATOM_OK) return;\n\told_val &= ')
    return source[:source.index('*/')+2]+'\n// Generated checked extract; deviations are in tools/import/extract_atom.py.\n'+arrays+core


def constants(header, source):
    lines=re.findall(r'^#define ATOM_\w+[ \t]+[^\n]+',header+'\n'+source.split('typedef struct {',1)[0],re.M)
    return header[:header.index('*/')+2]+'\n// Generated constants from original atom.h/atom.c.\n'+'\n'.join(lines)+'\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--import-linux', type=Path)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    dest = ROOT/'driver/amdgpu-import/reference/atom'
    if args.import_linux:
        dest.mkdir(parents=True, exist_ok=True)
        for name,path in SOURCES.items():
            shutil.copyfile(args.import_linux/path, dest/name)
    outputs = {'atom_layouts.inc': layouts((dest/'atomfirmware.h').read_text()),
               'atom_opcodes.inc': opcodes((dest/'atom.c').read_text()),
               'atom_constants.inc': constants((dest/'atom.h').read_text(),(dest/'atom.c').read_text()),
               'atom_interpreter.inc': interpreter((dest/'atom.c').read_text())}
    for name,text in outputs.items():
        out = ROOT/'driver/shim'/name
        if args.check:
            if out.read_text() != text:
                raise SystemExit('stale '+name)
        else:
            out.write_text(text, newline='\n')
    print('ATOM layouts/opcodes '+('checked' if args.check else 'extracted'))


if __name__ == '__main__':
    main()

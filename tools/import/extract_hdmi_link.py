"""Reproduce MIT AMD DCN10 HDMI stream/AVI code and ATOM argument layouts."""
import argparse
from pathlib import Path
import re
import shutil
from extract_display import extract

ROOT = Path(__file__).resolve().parents[2]
DC = 'drivers/gpu/drm/amd/display'
SOURCES = {
    'stream.c': DC+'/dc/dio/dcn10/dcn10_stream_encoder.c',
    'stream20.c': DC+'/dc/dio/dcn20/dcn20_stream_encoder.c',
    'stream32.c': DC+'/dc/dio/dcn32/dcn32_dio_stream_encoder.c',
    'link10.c': DC+'/dc/dio/dcn10/dcn10_link_encoder.c',
    'link20.c': DC+'/dc/dio/dcn20/dcn20_link_encoder.c',
    'hwseq201.c': DC+'/dc/hwss/dcn201/dcn201_hwseq.c',
    'resource.c': DC+'/dc/core/dc_resource.c',
    'set_mode_types.h': DC+'/include/set_mode_types.h',
    'dc_hw_types.h': DC+'/dc/dc_hw_types.h',
    'transform.h': DC+'/dc/inc/hw/transform.h',
    'dc_types.h': DC+'/dc/dc_types.h',
}

def declaration(text, kind, name):
    m = re.search(r'^'+kind+r'\s+'+name+r'\s*\{.*?^\};', text, re.M|re.S)
    if not m:
        raise ValueError('missing '+name)
    return m.group()

def generate(ref):
    stream = (ref/'stream.c').read_text()
    mode = (ref/'set_mode_types.h').read_text()
    hw = (ref/'dc_hw_types.h').read_text()
    xf = (ref/'transform.h').read_text()
    atom = (ROOT/'driver/amdgpu-import/reference/atom/atomfirmware.h').read_text()
    # Exact AMD layout declarations, separated from Linux header dependencies.
    layouts = [mode[:mode.index('*/')+2], '// Generated by extract_hdmi_link.py.',
               '#pragma pack(push, 1)']
    for kind, name in [('struct','hdmi_info_frame_header'), ('struct','info_packet_raw_data'),
                       ('union','hdmi_info_packet')]:
        layouts.append(declaration(mode,kind,name))
    layouts.append('#pragma pack(pop)')
    for name in ('dc_color_space','dc_aspect_ratio','scanning_type','dc_timing_3d_format',
                 'dc_color_depth','dc_pixel_encoding'):
        layouts.append(declaration(hw,'enum',name))
    layouts.append(declaration((ref/'dc_types.h').read_text(),'enum','display_content_type'))
    for name in ('colorimetry','colorimetry_ext','active_format_info','active_format_aspect_ratio',
                 'bar_info','picture_scaling','rgb_quantization_range','yyc_quantization_range'):
        layouts.append(declaration(xf,'enum',name))
    for name in ('dig_encoder_stream_setup_parameters_v1_5','dig_transmitter_control_parameters_v1_6',
                 'dig_transmitter_control_ps_allocation_v1_6'):
        layouts.append(declaration(atom,'struct',name))
    for name in ('atom_dig_encoder_control_action','atom_dig_transmitter_control_action'):
        layouts.append(declaration(atom,'enum',name))
    functions = extract(stream, ['enc1_update_generic_info_packet',
                                 'enc1_stream_encoder_set_stream_attribute_helper'])
    functions += extract((ref/'stream20.c').read_text(), ['enc2_update_hdmi_info_packet'])
    # The register portion of AMD's stream attribute function; caller supplies the
    # checked ATOM call first. Audio and final unmute stay in the existing audio owner.
    full = extract(stream,['enc1_stream_encoder_hdmi_set_stream_attribute'])
    start = full.index('\tenc1_stream_encoder_set_stream_attribute_helper(enc1, crtc_timing);')
    end = full.index('\t/* following belongs to audio */')
    functions += '\nstatic void hdmi_stream_registers(struct dcn10_stream_encoder *enc1,\n' \
                 '    struct dc_crtc_timing *crtc_timing, int actual_pix_clk_khz)\n{\n' + full[start:end]+'}\n'
    return {'hdmi_link_layouts.inc':'\n\n'.join(layouts)+'\n',
            'hdmi_link_stream.inc':functions,
            'hdmi_link_avi.inc':extract((ref/'resource.c').read_text(),['set_avi_info_frame'])}

def main():
    ap=argparse.ArgumentParser(__doc__)
    ap.add_argument('--import-linux',type=Path)
    ap.add_argument('--check',action='store_true')
    a=ap.parse_args()
    if a.check and a.import_linux: ap.error('check cannot import')
    ref=ROOT/'driver/amdgpu-import/reference/hdmi-link'
    if a.import_linux:
        ref.mkdir(exist_ok=True)
        for name, path in SOURCES.items(): shutil.copyfile(a.import_linux/path,ref/name)
    for name, contents in generate(ref).items():
        out=ROOT/'driver/shim'/name
        if a.check:
            if out.read_text()!=contents: raise SystemExit('stale '+name)
        else: out.write_text(contents,newline='\n')
    print('HDMI stream/AVI/layout extracts '+('checked' if a.check else 'written'))

if __name__=='__main__': main()

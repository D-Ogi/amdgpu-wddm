#!/usr/bin/env python3
"""Extract AMD's default/requested tap selection block, without DPP/MMIO context."""
import argparse
import hashlib
from extract_scaler_geometry import ROOT, REF, COMMIT, extract

OUT = ROOT / 'driver/shim/generated/dc_scaler_taps.inc'


def generate():
    raw = (REF / 'dcn201_dpp.c').read_bytes()
    text = raw.decode('utf-8')
    function = extract(text, 'dpp201_get_optimal_number_of_taps')
    start = function.index('\t/* Set default taps if none are provided */')
    end = function.index('\n\tif (!dpp->ctx->dc->debug.always_scale)', start)
    fixed = (REF / 'fixed31_32.h').read_text(encoding='utf-8')
    pieces = ['/* SPDX-License-Identifier: MIT */',
              '/* Generated by tools/import/extract_scaler_taps.py. Do not edit.\n'
              f' * PROVENANCE: Linux amdgpu DC, MIT, {COMMIT}.\n'
              f' * dcn201_dpp.c SHA256 {hashlib.sha256(raw).hexdigest()}\n'
              ' * The selection block is verbatim, in a new context-free wrapper.\n'
              ' * Format/range validation and identity bypass belong to the adapter. */',
              text[:text.index('*/') + 2],
              fixed[:fixed.index('*/') + 2], extract(fixed, 'dc_fixpt_ceil'),
              'static void amd_select_taps(struct scaler_data *scl_data,\n'
              '                            const struct scaling_taps *in_taps)\n{\n'
              + function[start:end].rstrip() + '\n}']
    return ('\n\n'.join(pieces).rstrip() + '\n').encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = generate()
    if args.check:
        if OUT.read_bytes() != data:
            raise SystemExit('Scaler tap extraction is stale')
    else:
        OUT.write_bytes(data)
    print('Scaler tap extraction OK')


if __name__ == '__main__':
    main()

"""Generate an exhaustive, fail-closed HDMI field policy from pinned AMD sources.

Masks describe layout, not access semantics. REG_UPDATE/SET uses provide positive
configuration evidence, with reviewed command/status exceptions. Unused fields
remain UNKNOWN and cannot be introduced by a write or replayed during restore.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / 'driver/amdgpu-import/reference/hdmi-link'
HEADER = ROOT / 'third_party/linux-amdgpu/dcn_2_0_1_sh_mask.h'


def generate():
    code = (ROOT / 'driver/shim/bc250_hdmi_link.c').read_text()
    macro = code.split('#define WRITE_REGS(X)', 1)[1].split('#define REG_ITEM', 1)[0]
    regs = ['DIG0_' + x for x in re.findall(r'X\((\w+)\)', macro)] + ['DIO_MEM_PWR_CTRL']
    evidence = {}
    for path in sorted(REF.glob('*.c')):
        source = path.read_text()
        for match in re.finditer(r'REG_(UPDATE|SET)(?:_\d+)?\s*\((.*?)\);', source, re.S):
            args = [s.strip() for s in match[2].split(',')]
            if not re.fullmatch(r'\w+', args[0]):
                continue
            start = 2 if match[1] == 'SET' else 1
            for field in args[start::2]:
                if re.fullmatch(r'\w+', field):
                    evidence.setdefault((args[0], field), f'{path.name}:{source[:match.start()].count(chr(10))+1} REG_{match[1]}')
    rows = []
    for line, text in enumerate(HEADER.read_text().splitlines(), 1):
        match = re.match(r'#define (\w+)__(\w+)_MASK\s+(0x[0-9A-Fa-f]+)L?$', text)
        if not match or match[1] not in regs:
            continue
        reg, field, value = match.groups()
        short = reg.removeprefix('DIG0_')
        usage = evidence.get((short, field))
        kind = 'configuration' if usage else 'unknown'
        if re.fullmatch(r'DIG0_AFMT_GENERIC_(HDR|[0-7])', reg):
            kind, usage = 'packet_data', 'stream.c:90-125 indexed header/payload writes then update; no immediate readback or old-data restore contract'
        if reg == 'DIO_MEM_PWR_CTRL':
            kind, usage = 'configuration', 'hwseq201.c:362 REG_WRITE(DIO_MEM_PWR_CTRL, 0) memory power control'
        if field == 'DIG_START':
            kind, usage = 'command', 'stream.c:1004-1006 resync FIFO command'
        elif field == 'AFMT_GENERIC_CONFLICT_CLR':
            kind, usage = 'command', 'stream20.c:242-243 clear HW/SW memory access conflict flag'
        elif re.fullmatch(r'AFMT_GENERIC[0-7]_(FRAME|IMMEDIATE)_UPDATE', field):
            kind, usage = 'command', 'stream.c:119-153 update request; stream20.c packet update'
        elif re.fullmatch(r'AFMT_GENERIC[0-7]_(FRAME|IMMEDIATE)_UPDATE_PENDING', field):
            if field == 'AFMT_GENERIC4_IMMEDIATE_UPDATE_PENDING':
                kind, usage = 'status', 'stream.c:851 REG_WAIT update completion'
            else:
                kind, usage = 'unknown', 'Pending family resembles stream.c:851, but no direct usage proof; refuse nonzero'
        elif field in ('AFMT_GENERIC_LOCK_STATUS', 'AFMT_GENERIC_CONFLICT'):
            kind, usage = 'status', 'stream20.c:233-240 REG_WAIT hardware lock/conflict'
        elif field == 'AFMT_AUDIO_CLOCK_ON':
            kind, usage = 'status', 'stream.c:1379 REG_WAIT clock acknowledgement'
        elif field == 'DIG_SYMCLK_FE_ON':
            kind, usage = 'status', 'stream32.c:314 REG_WAIT(DIG_FE_CNTL, DIG_SYMCLK_FE_ON, 1, 10, 5000)'
        elif field in ('HDMI_DB_PENDING', 'VUPDATE_DB_PENDING'):
            kind, usage = 'observed_volatile', 'audio41 lab readback 0x9001 -> 0x1000; volatility observed, RO semantics unproven'
        rows.append(dict(register=reg, field=field, mask=int(value, 16), kind=kind,
                         layout=f'dcn_2_0_1_sh_mask.h:{line}', usage=usage or 'No positive usage evidence; refuse nonzero unknown fields'))
    if set(regs) != {r['register'] for r in rows}:
        raise ValueError('unclassified writable register')
    lines = ['/* Generated by extract_hdmi_policy.py; masks are DWORD addresses. */']
    for reg in regs:
        masks = dict(configuration=0, command=0, status=0, unknown=0, packet_data=0)
        for row in (r for r in rows if r['register'] == reg):
            kind = 'status' if row['kind'] == 'observed_volatile' else row['kind']
            if any(v & row['mask'] for v in masks.values()):
                raise ValueError('overlapping fields ' + reg)
            masks[kind] |= row['mask']
        lines.append('{ BC250_REG_DMU_' + reg + '/4u, ' + ', '.join(f'UINT32_C(0x{x:08X})' for x in masks.values()) + ' },')
    return {'hdmi_link_policy.inc': '\n'.join(lines) + '\n',
            'hdmi_link_policy.json': json.dumps(rows, indent=2) + '\n'}


if __name__ == '__main__':
    ap = argparse.ArgumentParser(__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for name, content in generate().items():
        path = ROOT / 'driver/shim' / name
        if args.check:
            if path.read_text() != content:
                raise SystemExit('stale ' + name)
        else:
            path.write_text(content, newline='\n')
    print('HDMI field policy ' + ('checked' if args.check else 'generated'))

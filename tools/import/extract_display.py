"""Reproduce the AMD MIT function extracts used by the HDMI shim (Linux v6.18).

--import-linux PATH copies the named reference sources once. --check never writes.
The extracted bodies retain their upstream spelling; adaptations live in the shim.
"""
import argparse
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[2]
DC = "drivers/gpu/drm/amd/display/dc"
SPECS = {
    "dce_i2c_hw": ("dce/dce_i2c_hw.c", [
        "execute_transaction", "process_channel_reply", "is_engine_available", "is_hw_busy",
        "process_transaction", "set_speed", "acquire_engine", "cntl_stuck_hw_workaround"]),
    "link_detection": ("link/link_detection.c", ["query_dp_dual_mode_adaptor"]),
    "hdmi_audio": ("dio/dcn10/dcn10_stream_encoder.c", ["get_audio_clock_info", "enc1_se_setup_hdmi_audio"]),
    "hdmi_dto": ("dce/dce_audio.c", ["get_azalia_clock_info_hdmi"]),
}


def extract(source, names):
    # These pinned sources use a column-zero closing brace only at function end.
    license_end = source.index("*/") + 2
    chunks = [source[:license_end],
              "// Generated by tools/import/extract_display.py. Do not edit."]
    for name in names:
        pattern = rf"^(?:static )?(?:void|bool|uint32_t)\s+{re.escape(name)}\s*\([^;]*?\)\s*\n\{{.*?^\}}"
        matches = list(re.finditer(pattern, source, re.M | re.S))
        if len(matches) != 1:
            raise ValueError(f"expected one function {name}, got {len(matches)}")
        if name == "get_audio_clock_info":
            for table in ("audio_clock_info_table", "audio_clock_info_table_36bpc", "audio_clock_info_table_48bpc"):
                match = re.search(rf"^static const struct audio_clock_info {table}\[.*?^\}};", source, re.M | re.S)
                if not match:
                    raise ValueError(f"missing {table}")
                chunks.append(match.group())
        chunks.append(matches[0].group())
    return "\n\n".join(chunks) + "\n"


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--import-linux", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check and args.import_linux:
        parser.error("--check cannot import sources")
    for stem, (relative, names) in SPECS.items():
        ref = ROOT / "driver/amdgpu-import/reference" / f"{stem}.c"
        if args.import_linux:
            shutil.copyfile(args.import_linux / DC / relative, ref)
        generated = extract(ref.read_text(encoding="utf-8"), names)
        output = ROOT / "driver/shim" / f"{stem}.inc"
        if args.check:
            if output.read_text(encoding="utf-8") != generated:
                raise SystemExit(f"stale extract: {output}")
        else:
            output.write_text(generated, encoding="utf-8", newline="\n")
        print(f"{stem}: {len(names)} AMD functions {'checked' if args.check else 'extracted'}")


if __name__ == "__main__":
    main()

"""Extract AMD DCN201 timing operations and their named register contract (MIT)."""
import argparse
import json
from pathlib import Path
import re
import shutil
from extract_connector import functions

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {
    'optc10.c': 'drivers/gpu/drm/amd/display/dc/optc/dcn10/dcn10_optc.c',
    'optc10.h': 'drivers/gpu/drm/amd/display/dc/optc/dcn10/dcn10_optc.h',
    'optc20.c': 'drivers/gpu/drm/amd/display/dc/optc/dcn20/dcn20_optc.c',
    'optc201.c': 'drivers/gpu/drm/amd/display/dc/optc/dcn201/dcn201_optc.c',
    'optc201.h': 'drivers/gpu/drm/amd/display/dc/optc/dcn201/dcn201_optc.h',
}


def generate(ref):
    ten = (ref/'optc10.c').read_text()
    body = functions(ten, ['apply_front_porch_workaround', 'optc1_program_global_sync',
        'optc1_set_vtotal_min_max', 'optc1_set_vtg_params', 'optc1_program_timing',
        'optc1_disable_crtc'])
    body += functions((ref/'optc20.c').read_text(), ['optc2_enable_crtc'])
    header = (ref/'optc10.h').read_text() + (ref/'optc201.h').read_text()
    regs = sorted(set(re.findall(r'REG(?:_[A-Z0-9_]+)?\(\s*(\w+)', body)))
    regs = [r for r in regs if r not in ('',)]
    mapping = {}
    for reg in regs:
        matches = set(re.findall(r'SRI\('+reg+r',\s*(\w+),\s*inst\)', header))
        if len(matches) != 1:
            raise ValueError(f'register {reg}: {matches}')
        mapping[reg] = next(iter(matches))+'0_'+reg
    fields = sorted(set(re.findall(r'SF\((\w+),\s*(\w+),\s*mask_sh\)', header)))
    regtext = '// Generated by extract_optc.py; AMD DCN201 register aliases.\n'
    for reg, full in mapping.items():
        regtext += f'#define REG_{reg} BC250_REG_DMU_{full}\n'
        for source, field in fields:
            if source == full:
                regtext += f'#define MASK_{reg}_{field} {source}__{field}_MASK\n'
    return {
        'optc_timing.inc': body,
        'optc_registers.inc': regtext,
        'optc_registers.json': json.dumps(['mm'+x for x in mapping.values()], indent=2)+'\n',
    }


def main():
    ap = argparse.ArgumentParser(__doc__)
    ap.add_argument('--import-linux', type=Path)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    if args.check and args.import_linux:
        ap.error('check cannot import')
    ref = ROOT/'driver/amdgpu-import/reference/connector'
    if args.import_linux:
        for name, path in SOURCES.items():
            shutil.copyfile(args.import_linux/path, ref/name)
    for name, content in generate(ref).items():
        out = ROOT/'driver/shim'/name
        if args.check:
            if out.read_text() != content:
                raise SystemExit('stale '+name)
        else:
            out.write_text(content, newline='\n')
    print('OPTC extracts '+('checked' if args.check else 'written'))


if __name__ == '__main__':
    main()

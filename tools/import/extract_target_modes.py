"""Reproduce the progressive CTA target timings used by the EDID parser (MIT)."""
import argparse
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[2]
VICS = (1, 4, 16, 19, 31, 32, 33, 34, 60, 61, 62, 63, 64, 93, 94, 95, 96, 97)


def generate(text):
    table = text.split('static const struct drm_display_mode edid_cea_modes_1[] = {', 1)[1].split('\n};', 1)[0]
    rows = {}
    pattern = r'/\* (\d+) - .*?\*/\s*\{ DRM_MODE\("[^"]+", DRM_MODE_TYPE_DRIVER,\s*(.*?)\),'
    for match in re.finditer(pattern, table, re.S):
        vic = int(match[1])
        if vic not in VICS:
            continue
        args = [x.strip() for x in match[2].split(',')]
        numbers = [int(x) for x in args[:9]]
        clock, w, hs, he, ht, skew, h, vs, ve = numbers
        vt = int(args[9])
        flags = args[11]
        if skew or int(args[10]) or 'INTERLACE' in flags or 'DBLCLK' in flags:
            raise ValueError('non-progressive timing in selected VICs')
        polarity = (2 if 'PHSYNC' in flags else 0) | (4 if 'PVSYNC' in flags else 0)
        rows[vic] = f'    {{ {vic}, {{ {clock}, {w}, {ht-w}, {hs-w}, {he-hs}, {h}, {vt-h}, {vs-h}, {ve-vs}, {0x18 | polarity} }} }},'
    if set(rows) != set(VICS):
        raise ValueError('missing CTA timings')
    licence = text[:text.index('*/')+2]
    return licence + '\n// Generated by tools/import/extract_target_modes.py. Do not edit.\n' + '\n'.join(rows[v] for v in VICS) + '\n'


def main():
    ap = argparse.ArgumentParser(__doc__)
    ap.add_argument('--import-linux', type=Path)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    if args.check and args.import_linux:
        ap.error('check cannot import')
    ref = ROOT/'driver/amdgpu-import/reference/target-modes/drm_edid.c'
    if args.import_linux:
        ref.parent.mkdir(exist_ok=True)
        shutil.copyfile(args.import_linux/'drivers/gpu/drm/drm_edid.c', ref)
    out = ROOT/'driver/shim/cta_target_modes.inc'
    content = generate(ref.read_text())
    if args.check:
        if out.read_text() != content:
            raise SystemExit('stale CTA target modes')
    else:
        out.write_text(content, newline='\n')
    print('CTA target modes ' + ('checked' if args.check else 'written'))


if __name__ == '__main__':
    main()

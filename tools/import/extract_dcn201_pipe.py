def functions(source,names):
    result=[source[:source.index('*/')+2], '// Generated by extract_dcn201_pipe.py. Do not edit.']
    for name in names:
        found=re.findall(r'^(?:static )?(?:void|bool|uint8_t|uint32_t|int)\s+'+re.escape(name)+
            r'\s*\([^;]*?\)\s*\n\{.*?^\}',source,re.M|re.S)
        if len(found)!=1:raise ValueError('function '+name)
        result.extend(found)
    return '\n\n'.join(result)+'\n'


def generate():
    result={name:functions((REF/src).read_text(),names) for name,(src,names) in GROUPS.items()}
    result['pipe_did.inc'] = '\n'.join(declaration((REF/'clk.h').read_text(),'enum',name)
        for name in ['dentist_base_divider_id','dentist_divider_range'])+'\n'+result['pipe_did.inc']
    # Output/global helpers use OTG/OPP 0. HUBP helpers are remapped to slice
    # 0 or 1 by an independently generated register-name table below.
    result['pipe_dccg.inc']=result['pipe_dccg.inc'].replace('[otg_inst]','')
    result['pipe_mpc201.inc']=result['pipe_mpc201.inc'].replace('[opp_id]','')
    result['pipe_route.inc']='\n'.join(re.findall(r'^#define DCN10_DIG_FE_SOURCE_SELECT_.*$',
        (REF/'link10.c').read_text(),re.M))+'\n'+result['pipe_route.inc']
    layouts=[]
    for src,kind,names in [
        ('hw_shared.h','enum',['test_pattern_dyn_range','test_pattern_mode','test_pattern_color_format',
            'controller_dp_test_pattern','controller_dp_color_space']),
        ('dc_hw_types.h','enum',['dc_color_depth','dc_pixel_encoding']),
        ('dc_hw_types.h','struct',['tg_color']),('signal_types.h','enum',['signal_type']),
        ('grph_object_id.h','enum',['engine_id'])]:
        layouts += [declaration((REF/src).read_text(),kind,name) for name in names]
    result['pipe_layouts.inc']='// Original AMD declarations extracted by extract_dcn201_pipe.py.\n'+'\n'.join(layouts)+'\n'
    bodies='\n'.join(result.values())
    regs=set(re.findall(r'REG(?:_[A-Z0-9_]+)?\(\s*(\w+)',bodies))
    regs.update(['REFCLK_CNTL','DCHUBBUB_GLOBAL_TIMER_CNTL','CLK4_CLK_PLL_REQ','CLK4_CLK2_CURRENT_CNT','DPG_STATUS'])
    headers='\n'.join((REF/name).read_text() for name in SOURCES if name.endswith('.h'))
    aliases={}
    missing={'NOM_PARAMETERS_0','NOM_PARAMETERS_1','NOM_PARAMETERS_2','NOM_PARAMETERS_3','DCN_CUR1_TTU_CNTL1'}
    # The DCN201 HUBP register initializer omits VM-only NOM0..3 and cursor1.
    for r in sorted(regs):
        if r in missing:aliases[r]=None;continue
        found=set(re.findall(r'SRI\('+r+r',\s*(\w+),\s*(?:id|inst)\)',headers))
        if len(found)==1:full=next(iter(found))+'0_'+r
        elif r=='OTG_PIXEL_RATE_CNTL':full='OTG0_PIXEL_RATE_CNTL'
        elif r=='CLK4_CLK_PLL_REQ':full='CLK4_0_CLK4_CLK_PLL_REQ'
        elif r=='CLK4_CLK2_CURRENT_CNT':full='CLK4_0_CLK4_CLK2_CURRENT_CNT'
        elif r=='DIG_FIFO_STATUS':full='DIG0_DIG_FIFO_STATUS'
        elif r=='MUX':full='MPC_OUT0_MUX'
        else:full=r
        aliases[r]=('CLK' if r.startswith('CLK4_') else 'DMU', 'mm'+full)
    sys.path.insert(0,str(ROOT/'tools/regcalc'))
    from regcalc import RegMap,HDR_DIR
    maps={'DMU':RegMap('DMU',reg_header=HDR_DIR/'dcn_2_0_1_offset.h'),
          'CLK':RegMap('CLK',reg_header=HDR_DIR/'clk_11_0_1_offset.h')}
    masks={}
    for path in [HDR_DIR/'dcn_2_0_1_sh_mask.h',REF/'clk_mask.h']:
        for n,v in re.findall(r'^#define\s+(\w+_MASK)\s+(0x[0-9a-fA-F]+)[uUlL]*\s*$',path.read_text(),re.M):
            masks[n]=int(v,16)
    text='// Generated through regcalc from the pinned AMD register headers.\n'
    for r,value in aliases.items():
        if value is None:
            text+=f'#define PIPE_REG_{r} 0u\n'
            continue
        block,name=value
        offset=maps[block].byte_offset(name)
        text+=f'#define PIPE_REG_{r} 0x{offset:X}u\n'
        full=name[2:]
        for n in sorted(masks):
            if n.startswith(full+'__'):
                f=n[len(full)+2:-5]
                # DCCG uses array-field aliases, selected OTG0 only.
                alias=f.replace('OTG0_','OTG_',1) if r=='OTG_PIXEL_RATE_CNTL' else f
                text+=f'#define PIPE_MASK_{r}_{alias} {n}\n'
    # Absent optional registers are only accepted with a zero payload.
    for r in sorted(missing):
        candidates=re.findall(r'REG_SET(?:_\d)?\('+r+r',\s*0,\s*(\w+)',bodies)
        for f in candidates:text+=f'#define PIPE_MASK_{r}_{f} 0u\n'
    result['pipe_registers.inc']=text
    # HUBP-local names only. Do not infer a stride or remap output/global
    # state. Check every field mask before sharing the slice-0 setter masks.
    pairs=[]
    for value in aliases.values():
        if not value:continue
        block,name=value
        if block!='DMU' or not re.match(r'mm(?:HUBP|HUBPREQ|HUBPRET)0_',name):continue
        other=re.sub(r'0_', '1_',name,count=1)
        for mask,bits in masks.items():
            if mask.startswith(name[2:]+'__'):
                other_mask=other[2:]+mask[len(name[2:]):]
                if masks.get(other_mask)!=bits:raise ValueError('slice mask differs '+mask)
        pairs.append((name,other,maps[block].byte_offset(name),maps[block].byte_offset(other)))
    result['pipe_hubp_remap.inc']='// Generated by regcalc; no inferred register stride.\n'+''.join(
        f'case 0x{a:X}u: return 0x{b:X}u; // {n} -> {m}\n' for n,m,a,b in pairs)
    result['pipe_registers.json']=json.dumps({k:list(dict.fromkeys(
        [n for value in aliases.values() if value for b,n in [value] if b==k]+
        ([m for n,m,a,b in pairs] if k=='DMU' else []))) for k in maps},indent=2)+'\n'
    result['pipe_registers_readonly.json']=json.dumps({'CLK':['mmCLK4_0_CLK4_CLK_PLL_REQ','mmCLK4_0_CLK4_CLK2_CURRENT_CNT'],
        'DMU':['mmREFCLK_CNTL','mmDCHUBBUB_GLOBAL_TIMER_CNTL','mmDIG0_DIG_FIFO_STATUS','mmDPG0_DPG_STATUS']},indent=2)+'\n'
    return result


def main():
    p=argparse.ArgumentParser(__doc__);p.add_argument('--import-linux',type=Path);p.add_argument('--check',action='store_true')
    a=p.parse_args()
    if a.check and a.import_linux:p.error('check does not import')
    if a.import_linux:
        REF.mkdir(parents=True,exist_ok=True)
        manifest={'revision':'7d0a66e4bb9081d75c82ec4957c50034cb0ea449','license':'MIT','files':{}}
        for name,source in SOURCES.items():
            data=(a.import_linux/DC/source).read_bytes();(REF/name).write_bytes(data)
            manifest['files'][name]={'source':DC+source,'sha256':hashlib.sha256(data).hexdigest()}
        (REF/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    for n,v in json.loads((REF/'manifest.json').read_text())['files'].items():
        if hashlib.sha256((REF/n).read_bytes()).hexdigest()!=v['sha256']:raise SystemExit('changed reference '+n)
    for n,v in generate().items():
        if a.check:
            if (OUT/n).read_text()!=v:raise SystemExit('stale '+n)
        else:(OUT/n).write_text(v,newline='\n')
    print('DCN201 pipe extracts '+('checked' if a.check else 'written'))


if __name__=='__main__':main()

# Compiles the GLSL shaders of vkwbs cases 4 and 4b (shaders\) to SPIR-V and writes vk_wbs_spirv.h, the C arrays that
# vk_wbs_hang.c includes. The header is committed, so build.ps1 needs no shader compiler. Run this script again after
# a change of a shader, and commit the new header with it. Every module is checked with spirv-val (Vulkan 1.2).
#
#   pwsh tools\win\vkwbs\gen-spirv.ps1 [-Glslang <glslangValidator.exe>] [-SpirvVal <spirv-val.exe>]
param(
    [string]$Root = $(if ($env:BC250_ROOT) { $env:BC250_ROOT } else { (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path }),
    [string]$Glslang = '',
    [string]$SpirvVal = ''
)
$ErrorActionPreference = 'Stop'
if (-not $Glslang) { $Glslang = Join-Path $Root 'toolchain\vk-build\Library\bin\glslangValidator.exe' }
if (-not $SpirvVal) { $SpirvVal = Join-Path $Root 'toolchain\vk-build\Library\bin\spirv-val.exe' }
foreach ($t in @($Glslang, $SpirvVal)) { if (-not (Test-Path -LiteralPath $t)) { throw "not found: $t" } }
$version = (& $Glslang --version | Select-Object -First 1)
$tmp = Join-Path $Root 'scratch\tmp\vkwbs-spirv'
New-Item -ItemType Directory -Force $tmp | Out-Null
$shaders = [ordered]@{ point_vert = 'point.vert'; patch_tesc = 'patch.tesc'; patch_tese = 'patch.tese'; empty_comp = 'empty.comp'; scratch_comp = 'scratch.comp' }
$lines = @(
    '/* Generated by gen-spirv.ps1 from shaders\*. Do not edit; run gen-spirv.ps1 again after a shader change.',
    "   Compiler: $version (glslangValidator -V --target-env vulkan1.2). */",
    '#pragma once',
    '#include <stdint.h>')
foreach ($name in $shaders.Keys) {
    $src = Join-Path $PSScriptRoot "shaders\$($shaders[$name])"
    $spv = Join-Path $tmp "$name.spv"
    & $Glslang -V --target-env vulkan1.2 -o $spv $src | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "glslangValidator failed on $src ($LASTEXITCODE)" }
    & $SpirvVal --target-env vulkan1.2 $spv
    if ($LASTEXITCODE -ne 0) { throw "spirv-val failed on $spv ($LASTEXITCODE)" }
    $bytes = [IO.File]::ReadAllBytes($spv)
    $words = for ($i = 0; $i -lt $bytes.Length; $i += 4) { '0x{0:x8}u' -f [BitConverter]::ToUInt32($bytes, $i) }
    $lines += ''
    $lines += "/* shaders\$($shaders[$name]): $($bytes.Length) bytes */"
    $lines += "static const uint32_t spv_$name[] = {"
    for ($i = 0; $i -lt $words.Count; $i += 8) { $lines += '    ' + (($words[$i..([Math]::Min($i + 7, $words.Count - 1))]) -join ', ') + ',' }
    $lines += '};'
}
$h = Join-Path $PSScriptRoot 'vk_wbs_spirv.h'
[IO.File]::WriteAllText($h, ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
"wrote $h $((Get-FileHash $h).Hash)"

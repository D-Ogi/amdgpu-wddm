"""Generate the GFX10 wave field table from the imported AMD mask header."""
from pathlib import Path
import argparse
import hashlib
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SOURCE = ROOT / "third_party/linux-amdgpu/gc_10_1_0_sh_mask.h"
OUTPUT = HERE / "wave_fields.generated.h"
REGISTERS = (
    ("Status", "STATUS"), ("PcLo", "PC_LO"), ("PcHi", "PC_HI"),
    ("ExecLo", "EXEC_LO"), ("ExecHi", "EXEC_HI"), ("HwId1", "HW_ID1"),
    ("HwId2", "HW_ID2"), ("InstDw0", "INST_DW0"), ("GprAlloc", "GPR_ALLOC"),
    ("LdsAlloc", "LDS_ALLOC"), ("Trapsts", "TRAPSTS"), ("IbSts", "IB_STS"),
    ("IbSts2", "IB_STS2"), ("IbDbg1", "IB_DBG1"), ("M0", "M0"), ("Mode", "MODE"),
)


def generate():
    raw = SOURCE.read_bytes()
    source = raw.decode("ascii")
    macros = dict(re.findall(r"^#define\s+(\w+)\s+(0x[0-9a-fA-F]+)[UL]*\s*$", source, re.M))
    lines = [
        "/* Generated by gen_wave_decode.py. Do not edit.",
        " * PROVENANCE: Linux AMD register headers, MIT, third_party/linux-amdgpu.",
        " * Source: gc_10_1_0_sh_mask.h SHA-256 " + hashlib.sha256(raw).hexdigest(),
        " */",
        '#include "../../../third_party/linux-amdgpu/gc_10_1_0_sh_mask.h"',
        "static const char *const WaveRegisterNames[Bc250WaveRegisterCount] = {",
    ]
    lines += ['    "SQ_WAVE_' + name + '",' for _, name in REGISTERS]
    lines += ["};", "static const BC250_WAVE_FIELD WaveFields[] = {"]
    for enum, register in REGISTERS:
        prefix = "SQ_WAVE_" + register + "__"
        fields = [name[len(prefix):-len("__SHIFT")] for name in macros
                  if name.startswith(prefix) and name.endswith("__SHIFT")]
        if not fields:
            raise ValueError("no fields for " + register)
        for field in fields:
            shift = prefix + field + "__SHIFT"
            mask = prefix + field + "_MASK"
            if mask not in macros:
                raise ValueError("missing " + mask)
            if not 0 <= int(macros[shift], 16) < 32 or not 0 < int(macros[mask], 16) <= 0xffffffff:
                raise ValueError("invalid field " + field)
            lines.append(f'    {{ Bc250Wave{enum}, "{field}", {mask}, {shift} }},')
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            parser.exit(1, "wave decode table is stale: run gen_wave_decode.py\n")
    else:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()

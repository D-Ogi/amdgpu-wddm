# Generates driver/kmd/boot_logo_asset.inc from one of the project's mascot PNGs.
#
# The driver must not decode a PNG at device start, and the build must stay reproducible (/Brepro, no tool runs
# during the build), so the picture is turned into C source here and the result is checked into the repository.
# Re-run this script only to change the picture; the build never calls it.
#
# The format is the one driver/kmd/boot_logo.h describes: a palette of straight-alpha BGRA colours and, per row,
# runs of (count, palette index) ending in a zero count. Transparent pixels all share palette entry 0, so the
# margins of the figure cost two bytes a row.
#
# Usage:
#   python tools/win/make_boot_logo_asset.py \
#       --png tools/win/amdgpu_wddm_control/art/nagi/sheet-welcome@256.png \
#       --out driver/kmd/boot_logo_asset.inc
import argparse
import hashlib
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is needed to run this generator (it is not needed to build the driver)")


def quantise(image, colours):
    """Reduce to at most `colours` opaque colours, keeping the alpha channel intact."""
    rgb = image.convert("RGB").quantize(colors=colours, method=Image.MEDIANCUT, dither=Image.NONE)
    return rgb.convert("RGB"), image.getchannel("A")


def build(png, box, colours, alpha_levels):
    image = Image.open(png).convert("RGBA")
    bbox = image.getchannel("A").point(lambda v: 255 if v else 0).getbbox()
    if bbox is None:
        raise ValueError("the picture is fully transparent")
    image = image.crop(bbox)
    scale = min(box / image.width, box / image.height)
    size = (max(1, round(image.width * scale)), max(1, round(image.height * scale)))
    image = image.resize(size, Image.LANCZOS)

    rgb, alpha = quantise(image, colours)
    # Alpha is quantised too: it only has to carry the anti-aliased edge, and fewer levels means longer runs.
    # The ladder keeps both ends exact, so the inside of the figure stays fully opaque (the driver then writes
    # those pixels without reading the framebuffer back) and the outside stays fully transparent.
    levels = alpha_levels - 1
    alpha = alpha.point(lambda v: (v * levels + 127) // 255 * 255 // levels)

    width, height = image.size
    rgb_px, a_px = rgb.load(), alpha.load()
    keys = []
    counts = {}
    for y in range(height):
        row = []
        for x in range(width):
            a = a_px[x, y]
            key = (0, 0, 0, 0) if a == 0 else (rgb_px[x, y][2], rgb_px[x, y][1], rgb_px[x, y][0], a)
            counts[key] = counts.get(key, 0) + 1
            row.append(key)
        keys.append(row)

    # Colour and alpha were quantised separately, so their product can pass 256 entries. Keep the entries that
    # cover the most pixels and send each of the rest to the nearest kept colour: the ones that go are by
    # definition the rare ones, and the nearest kept entry is within one quantisation step of them.
    order = [(0, 0, 0, 0)]
    order += [k for k in sorted(counts, key=lambda k: (-counts[k], k)) if k != (0, 0, 0, 0)][:255]
    palette = {k: i for i, k in enumerate(order)}
    for key in counts:
        if key in palette:
            continue
        palette[key] = min(range(1, len(order)),
                           key=lambda i: sum((order[i][c] - key[c]) ** 2 for c in range(4)))
    indices = [[palette[k] for k in row] for row in keys]

    data = bytearray()
    for row in indices:
        x = 0
        while x < width:
            index, run = row[x], 1
            while x + run < width and row[x + run] == index and run < 255:
                run += 1
            data += bytes((run, index))
            x += run
        data.append(0)
    return width, height, order, bytes(data)


def emit(path, png, width, height, palette, data, source_hash):
    name = os.path.basename(png)
    out = [
        "/* SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0 */",
        "/* Generated by tools/win/make_boot_logo_asset.py from %s" % name,
        " * (SHA-256 %s). Do not edit: re-run the generator." % source_hash,
        " * %u x %u, %u palette entries, %u bytes of run data. */" % (width, height, len(palette), len(data)),
        "",
        "static const BC250_LOGO_COLOR Bc250BootLogoPalette[%u] = {" % len(palette),
    ]
    for i in range(0, len(palette), 6):
        row = "".join("{%3u,%3u,%3u,%3u}," % c for c in palette[i:i + 6])
        out.append("    " + row)
    out += ["};", "", "static const unsigned char Bc250BootLogoData[%u] = {" % len(data)]
    for i in range(0, len(data), 16):
        out.append("    " + "".join("0x%02x," % b for b in data[i:i + 16]))
    out += [
        "};",
        "",
        "static const BC250_BOOT_LOGO Bc250BootLogoNagi = {",
        "    %u, %u, %u, %u, Bc250BootLogoPalette, Bc250BootLogoData" % (width, height, len(palette), len(data)),
        "};",
        "",
    ]
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--png", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--box", type=int, default=160, help="the longer side of the generated picture")
    ap.add_argument("--colours", type=int, default=96)
    ap.add_argument("--alpha-levels", type=int, default=9)
    ap.add_argument("--budget", type=int, default=48 * 1024, help="refuse an asset larger than this many bytes")
    a = ap.parse_args()

    with open(a.png, "rb") as f:
        source_hash = hashlib.sha256(f.read()).hexdigest().upper()
    width, height, palette, data = build(a.png, a.box, a.colours, a.alpha_levels)
    total = len(data) + len(palette) * 4
    if total > a.budget:
        sys.exit("asset is %u bytes, over the budget of %u" % (total, a.budget))
    emit(a.out, a.png, width, height, palette, data, source_hash)
    print("%s: %u x %u, %u colours, %u + %u = %u bytes (budget %u)"
          % (a.out, width, height, len(palette), len(data), len(palette) * 4, total, a.budget))


if __name__ == "__main__":
    main()

# Builds amdgpu_wddm_d3d12pso.exe: the programs with the SDK's dxc into gen\*.h, then one cl invocation, then the
# CPU-only gates (--help 0, --invalid 2, --selftest 0). The previous exe stays under retained\ by its hash.
# The pattern is the one of ..\conformance-clients\build.ps1, including the dxc identity record in gen\dxc.txt.
param(
    [Parameter(Mandatory)][string]$Kits,
    [string]$Out,
    [string]$KitVersion = '10.0.26100.0',
    [ValidateSet('x64', 'x86')][string]$Arch = 'x64',
    # Pixel programs, each with its own unrolled round count, so each is a different program for the engine.
    [ValidateRange(2, 64)][int]$Variants = 16
)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$sdk = Join-Path $Kits 'microsoft.windows.sdk.cpp\c'
$sdkLib = Join-Path $Kits "microsoft.windows.sdk.cpp.$Arch\c"
$dxc = Join-Path $sdk "bin\$KitVersion\x64\dxc.exe"
if (-not (Test-Path -LiteralPath $dxc)) { throw "dxc not found: $dxc" }
if (-not (Test-Path -LiteralPath $sdkLib)) { throw "SDK libraries for $Arch not found: $sdkLib" }

# The workspace root: BC250_ROOT when it is set, else the grandparent of -Kits, which is <workspace>\toolchain\nuget.
# Taken from -Kits and never from this script's own place: a build in a git worktree sits under <workspace>\scratch\.
$root = if ($env:BC250_ROOT) { [IO.Path]::GetFullPath($env:BC250_ROOT) } else { (Resolve-Path (Join-Path $Kits '..\..')).Path }
if (-not $Out) { $Out = Join-Path $root "scratch\build\amdgpu_wddm_d3d12pso-$Arch" }

$vs = & "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" -latest -products * -property installationPath
$msvc = Get-ChildItem (Join-Path $vs 'VC\Tools\MSVC') -Directory | Sort-Object Name | Select-Object -Last 1
$cl = Join-Path $msvc.FullName "bin\Hostx64\$Arch\cl.exe"
if (-not (Test-Path -LiteralPath $cl)) { throw "cl for $Arch not found: $cl" }
New-Item -ItemType Directory -Force $Out | Out-Null
# Temporary files of the compiler stay in the workspace, never on the system drive.
$env:TEMP = Join-Path $root 'scratch\tmp'; $env:TMP = $env:TEMP
New-Item -ItemType Directory -Force $env:TEMP | Out-Null

# The programs: one vertex program and $Variants pixel programs, variant v with 4 * (v + 1) unrolled rounds. dxc is
# deterministic, so a rebuild with the same SDK writes the same bytes as the tracked headers.
$gen = Join-Path $here 'gen'
New-Item -ItemType Directory -Force $gen | Out-Null
$programs = @(@{ Name = 'pso_vs'; Profile = 'vs_6_0'; Entry = 'vs_main'; Defines = @() })
$rounds = @()
for ($v = 0; $v -lt $Variants; $v++) {
    $rounds += 4 * ($v + 1)
    $programs += @{ Name = ('pso_ps_{0:d2}' -f $v); Profile = 'ps_6_0'; Entry = 'ps_main'; Defines = @('-D', "ROUNDS=$(4 * ($v + 1))") }
}
$dxcVersion = (& $dxc --version 2>&1 | Select-Object -First 1)
# The workspace root is written as <BC250_ROOT>, so the record does not depend on the caller's -Kits spelling.
$sanitized = $dxc.StartsWith($root, [System.StringComparison]::OrdinalIgnoreCase)
$dxcPath = if ($sanitized) { '<BC250_ROOT>' + $dxc.Substring($root.Length) } else { $dxc }
$log = @("dxc $dxcPath", "dxc version $dxcVersion", "dxc sha256 $((Get-FileHash -LiteralPath $dxc).Hash)")
$source = Join-Path $here 'shaders\d3d12pso.hlsl'
foreach ($p in $programs) {
    $header = Join-Path $gen "$($p.Name).h"
    $arguments = @('-nologo', '-T', $p.Profile, '-E', $p.Entry) + $p.Defines + @('-Vn', "g_$($p.Name)", '-Fh', $header, $source)
    & $dxc @arguments
    if ($LASTEXITCODE -ne 0) { throw "dxc failed for $($p.Name) ($LASTEXITCODE)" }
    # dxc writes CRLF; .gitattributes checks these headers out with LF, so the line endings are normalized here.
    [IO.File]::WriteAllText($header, ([IO.File]::ReadAllText($header) -replace "`r`n", "`n"))
    $log += "dxc -T $($p.Profile) -E $($p.Entry) $($p.Defines -join ' ') -Fh gen\$($p.Name).h shaders\d3d12pso.hlsl"
}

# gen\variants.h is generated as well: the table the client reads, with the round count next to every program.
$lines = @(
    '// SPDX-License-Identifier: MIT',
    '// Generated by build.ps1 from shaders\d3d12pso.hlsl. Do not edit.',
    '#pragma once'
)
foreach ($p in $programs) { $lines += "#include `"$($p.Name).h`"" }
$lines += @(
    '',
    'struct PsoVariant {',
    '    const unsigned char* code;',
    '    unsigned size;',
    '    unsigned rounds;        // unrolled rounds of the pixel program, the CPU mirror uses the same count',
    '};',
    '',
    "static constexpr unsigned kPsoVariantCount = $Variants;",
    'static const PsoVariant g_pso_variants[kPsoVariantCount] = {'
)
for ($v = 0; $v -lt $Variants; $v++) {
    $name = 'pso_ps_{0:d2}' -f $v
    $lines += "    {{ g_{0}, (unsigned)sizeof(g_{0}), {1} }}," -f $name, $rounds[$v]
}
$lines += '};'
[IO.File]::WriteAllText((Join-Path $gen 'variants.h'), ($lines -join "`n") + "`n")

# gen\dxc.txt is a tracked record, written only when it really changed and only when the dxc path came out sanitized.
$record = Join-Path $gen 'dxc.txt'
$current = if (Test-Path -LiteralPath $record) { @(Get-Content -LiteralPath $record) } else { @() }
if ($current.Count -eq $log.Count -and -not (Compare-Object $current $log -SyncWindow 0)) {
    Write-Host '  gen\dxc.txt unchanged'
} elseif ($sanitized) {
    $log | Set-Content -LiteralPath $record -Encoding ascii
    Write-Host '  gen\dxc.txt rewritten'
} else {
    Write-Warning ("dxc is outside the workspace root $root, so gen\dxc.txt keeps its tracked content. " +
        'Pass -Kits under the workspace, or set BC250_ROOT, to record the dxc identity.')
}

# A reviewed artifact is never lost to a rebuild: the existing binary stays under retained\ by its full hash.
$exe = Join-Path $Out 'amdgpu_wddm_d3d12pso.exe'
if (Test-Path -LiteralPath $exe) {
    $hash = (Get-FileHash -LiteralPath $exe).Hash
    $keep = Join-Path $Out "retained\amdgpu_wddm_d3d12pso-$hash.exe"
    if (-not (Test-Path -LiteralPath $keep)) {
        New-Item -ItemType Directory -Force (Split-Path -Parent $keep) | Out-Null
        Copy-Item -LiteralPath $exe -Destination $keep
    }
    Write-Host "  previous artifact retained as retained\amdgpu_wddm_d3d12pso-$hash.exe"
}

$env:INCLUDE = ''; $env:LIB = ''
$clArgs = @('/nologo', '/W4', '/WX', '/O2', '/MT', '/EHsc', '/std:c++17', '/DUNICODE', '/D_UNICODE', "/I$here",
    "/I$(Join-Path $msvc.FullName 'include')", "/I$sdk\Include\$KitVersion\ucrt", "/I$sdk\Include\$KitVersion\um",
    "/I$sdk\Include\$KitVersion\shared", "/I$sdk\Include\$KitVersion\winrt",
    "/Fo$Out\amdgpu_wddm_d3d12pso.obj", "/Fe$exe", (Join-Path $here 'd3d12pso.cpp'), '/link',
    "/LIBPATH:$(Join-Path $msvc.FullName "lib\$Arch")", "/LIBPATH:$sdkLib\ucrt\$Arch", "/LIBPATH:$sdkLib\um\$Arch",
    'dxgi.lib', 'bcrypt.lib', 'kernel32.lib', 'user32.lib')
& $cl @clArgs | ForEach-Object { if ($_ -notmatch '^\s*$|^Microsoft|^Copyright|^\S+\.cpp$') { Write-Host "  $_" } }
if ($LASTEXITCODE -ne 0) { throw "cl failed ($LASTEXITCODE)" }

# The CPU-only gates. No device is created here: the lab runs the client, this PC only proves it is whole.
& $exe --help | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'help check failed' }
& $exe --invalid 2>&1 | Out-Null
if ($LASTEXITCODE -ne 2) { throw "invalid CLI accepted ($LASTEXITCODE)" }
& $exe --count 0 2>&1 | Out-Null
if ($LASTEXITCODE -ne 2) { throw "--count 0 accepted ($LASTEXITCODE)" }
& $exe --selftest | Tee-Object -Variable selftest | Out-Null
if ($LASTEXITCODE -ne 0) { $selftest | Write-Host; throw 'selftest failed' }
$selftest | Select-Object -Last 1 | ForEach-Object { Write-Host "  $_" }
Get-Item $exe | ForEach-Object { '{0,9}  {1}  sha256 {2}' -f $_.Length, $_.Name, (Get-FileHash -LiteralPath $_.FullName).Hash }

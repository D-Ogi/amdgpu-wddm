"""Generate the common state contract. --check is read-only and detects drift."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KINDS = {'setting': 'SETTING', 'record': 'RECORD', 'volatile': 'VOLATILE'}
TYPES = {'dword': 'DWORD', 'qword': 'QWORD', 'sz': 'SZ', 'multi_sz': 'MULTI_SZ', 'binary': 'BINARY'}
GROUPS = {'none','cpu','cu','dpm','fan','hwmon','interop'}

def load(path):
    catalog=json.loads(path.read_text(encoding='utf-8'))
    if catalog['schema']!=2 or catalog['service']!='bc250kmd' or catalog['defaults_child']!='DefaultsV2':
        raise ValueError('unsupported state schema')
    seen=set()
    for s in catalog['values']:
        key=(s['path'].lower(),s['name'].lower())
        if key in seen or not s['name'].isascii() or not s['name'].isalnum(): raise ValueError('duplicate/invalid setting')
        seen.add(key)
        if s['path'] and any(not part.isascii() or not part.isalnum() for part in s['path'].split('/')):
            raise ValueError('invalid child')
        if s['kind'] not in KINDS or s['type'] not in TYPES or s['group'] not in GROUPS:
            raise ValueError('invalid kind/type/group')
        if not 0<=s['min']<=s['max']<=0xffffffff or not 1<=s['max_bytes']<=262144:
            raise ValueError('invalid bound')
        if s['type'] in ('dword','qword') and s['max_bytes']!={'dword':4,'qword':8}[s['type']]:
            raise ValueError('invalid fixed size')
        if s['access'] not in ('admin','driver','admin_clear') or s['readable'] not in ('user','admin'):
            raise ValueError('invalid access')
        if s['kind']!='setting' and (s['factory'] is not None or s['code'] is not None):
            raise ValueError('records must not have defaults')
        if s['kind']=='volatile' and s['migration']!='never': raise ValueError('volatile migration')
        for v in s['allowed']+[s[k] for k in ('factory','code','legacy_absent') if s[k] is not None]:
            if type(v)!=int or not s['min']<=v<=s['max'] or (s['allowed'] and v not in s['allowed']):
                raise ValueError('default/enum out of range: '+s['name'])
    return catalog

def render(catalog):
    canonical=json.dumps(catalog,sort_keys=True,separators=(',',':')).encode()
    identity=hashlib.sha256(canonical).hexdigest()
    lines=['// Generated by tools/state/generate.py; edit catalog.json.',
           '#pragma once', '#define AMDGPU_STATE_SCHEMA_VERSION 2u',
           f'#define AMDGPU_STATE_CATALOG_ID "{identity}"',
           f'#define AMDGPU_STATE_COUNT {len(catalog["values"])}u']
    for i,s in enumerate(catalog['values']):
        if s['allowed']:
            lines.append(f'static const unsigned int StateAllowed{i}[] = {{'+', '.join(str(v)+'u' for v in s['allowed'])+'};')
    lines.append('static const AMDGPU_STATE_SPEC StateCatalog[] = {')
    defaults=['; Generated by tools/state/generate.py; copied into the package INF.', '[AmdgpuStateDefaults]',
              f'HKR,Parameters\\DefaultsV2,CatalogId,0x00000000,"{identity}"',
              'HKR,Parameters\\DefaultsV2,PackageProductVersion,0x00000000,%PackageProductVersion%',
              'HKR,Parameters\\DefaultsV2,Schema,0x00010001,2']
    for i,s in enumerate(catalog['values']):
        fields=[json.dumps(s['path'].replace('/','\\')),json.dumps(s['name']),
            'AMDGPU_STATE_'+KINDS[s['kind']], 'AMDGPU_STATE_'+TYPES[s['type']],
            str(s['max_bytes'])+'u',str(s['min'])+'u',str(s['max'])+'u',
            f'StateAllowed{i}' if s['allowed'] else '0',str(len(s['allowed']))+'u',
            str(int(s['factory'] is not None))+'u',str(s['factory'] or 0)+'u',
            str(int(s['code'] is not None))+'u',str(s['code'] or 0)+'u',
            'AMDGPU_STATE_'+s['access'].upper(),str(int(s['readable']=='admin'))+'u',
            'AMDGPU_STATE_GROUP_'+s['group'].upper(),str(int(s['migration']=='explicit-off-if-absent'))+'u']
        lines.append('    {'+', '.join(fields)+'},')
        if s['factory'] is not None:
            if s['path'] or s['type']!='dword': raise ValueError('unsupported package default')
            defaults.append(f'HKR,Parameters\\DefaultsV2,{s["name"]},0x00010001,{s["factory"]}')
    lines.append('};')
    package=b'AMDST02\0'+struct.pack('<II',2,len(catalog['values']))+identity.encode('ascii')
    package+=b''.join(struct.pack('<III',i,int(s['factory'] is not None),s['factory'] or 0)
                      for i,s in enumerate(catalog['values']))
    return {'driver/state/catalog.generated.h':('\n'.join(lines)+'\n').encode(),
            'driver/state/defaults.generated.inf':('\n'.join(defaults)+'\n').encode(),
            'driver/state/amdgpu-state.bin':package}

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    catalog=load(ROOT/'driver/state/catalog.json')
    files=render(catalog)
    release_path='tools/release/installer/registry-defaults.json'
    release=json.loads((ROOT/release_path).read_text(encoding='utf-8'))
    release['defaults']['parameters']={s['name']:s['factory'] for s in catalog['values'] if s['factory'] is not None}
    files[release_path]=(json.dumps(release,indent=2,ensure_ascii=True)+'\n').encode('ascii')
    inf=ROOT/'driver/kmd/bc250kmd.inf'
    text=inf.read_text(encoding='ascii')
    begin='; BEGIN GENERATED STATE DEFAULTS\n'
    end='; END GENERATED STATE DEFAULTS'
    if text.count(begin)!=1 or text.count(end)!=1: raise SystemExit('INF state markers missing/duplicated')
    first=text.index(begin)+len(begin);last=text.index(end,first)
    generated=files['driver/state/defaults.generated.inf'].decode('ascii')
    files['driver/kmd/bc250kmd.inf']=(text[:first]+generated+text[last:]).replace('\n','\r\n').encode('ascii')
    changed=[]
    for relative,text in files.items():
        path=ROOT/relative
        if not path.exists() or path.read_bytes()!=text:
            changed.append(relative)
            if not args.check: path.write_bytes(text)
    if args.check and changed: raise SystemExit('Generated state files differ: '+', '.join(changed))
    print('state catalog: '+('verified' if args.check else 'generated'))

if __name__=='__main__': main()

#!/bin/sh
# The read-only half of the next Linux session on unit A, as one script for the diagnostic stick.
#
#   sh linux_session_collect.sh [all | <step> ...]
#
# It runs on Alpine from the stick, from RAM, as root. Everything lands in ONE timestamped directory
# (default /tmp/bc250-<UTC stamp>, override with BC250_OUT) and a progress line goes to stdout as it
# happens, so the PC has the session as it runs and a hang names its cause. No step aborts the run:
# every command's exit code is written to commands.log, every step's to steps.log, and the next step
# starts anyway.
#
# WHAT THIS SCRIPT DOES NOT DO, and none of it is negotiable:
#   - no register WRITE of any kind. The stick must be booted bc250.mode=readonly, in which even
#     diag.py's two standard probe writes (GRBM_GFX_INDEX bank select, SCRATCH_REG0 pattern) are
#     skipped. Every read here goes through sweep_stream.py (raw BAR5 mmap, read-only) or regs2.py
#     (amdgpu's own amdgpu_regs2 accessor under its mutex).
#   - no amdgpu_gpu_recover (facts M53), no modprobe -r amdgpu and no second modprobe in one boot
#     (M42, M55), no suspend (M56), nothing to NVRAM, the firmware or a disk.
#   - the debugfs files that DO something when read - amdgpu_test_ib, amdgpu_gpu_recover,
#     amdgpu_evict_vram, amdgpu_evict_gtt, amdgpu_benchmark, amdgpu_preempt_ib, amdgpu_force_sclk,
#     amdgpu_gfxoff, ras_ctrl - are named nowhere below, and no debugfs directory is globbed.
#   - pp_dpm_*, pp_od_clk_voltage, power_dpm_* and pp_power_profile_mode are only ever read. No SMU
#     message is sent by hand and no clock is changed.
#   - it redacts NOTHING. That is deliberate: a capture that edits itself is a capture nobody can
#     check. MAC addresses, the Wi-Fi SSID, serial numbers, UUIDs and the EDID are stripped on the
#     development PC, once, with experiments/E13-linux-reference-2/redact.py, before the files are
#     copied into evidence/. REDACT-BEFORE-COMMIT.txt in the output directory says so again.
#
# Only tools the stick actually has: busybox sh/dd/od/awk/sed/grep/wc/tr/find/timeout/sha256sum,
# python3 3.14, lspci, and ftrace through /sys/kernel/tracing. There is no umr, no trace-cmd, no
# devmem, no xxd, no libdrm and no compiler here; rings are dumped raw and decoded on the PC.
#
# Files it expects next to itself (pushed from the PC into the same directory), each optional -
# a missing one is logged as SKIP and the run continues:
#   regs2.py           experiments/E13-linux-reference-2/regs2.py
#   lists.json         experiments/E13-linux-reference-2/lists.json (gen_lists.py made it)
#   info.py info.json  experiments/E13-linux-reference-2/
#   dmulists.json      generated by gen_dmu.py: the DMU set for regs2.py
#   dmusweep.json      generated by gen_dmu.py: the DMU set for sweep_stream.py
#   vmlists.json       experiments/E17-linux-reference-3/vmlists.json
#   sweep.json         evidence/linux/2026-09-21-E03-init-trace/sweep.json
#   skip-conservative.txt   the same directory: register names that must not be read
#
# Steps, in order. "all" runs them all; naming steps runs those, in the order given.
#   pre        kernel, PCI view, interrupts, M.2 root port. No GPU register is read
#   sweep      the pre-driver register sweep, streamed (wishlist L1)
#   dmupre     the FIRMWARE's DMU state by raw BAR5 read, before any driver (L21)
#   load       modprobe amdgpu under the event trace (L9, L16)
#   state      post-init state, rings and MQDs, named registers (L2 L3 L4 L7 L8)
#   dmupost    the same DMU set through amdgpu_regs2, as the second method (L20 idle leg, L21)
#   vmregs     412 named VM registers of both hubs, no client (E17 base)
#   extras     ip_discovery, DTN log, connectors, GDS/OA, sa_info, fence_info (L8, L19)
#   info       every AMDGPU_INFO query (facts M46 check)
#   power      the whole power surface, idle, plus the SMU messages amdgpu itself sent (L10)
#   close      temperature, dmesg tail, inventory
#
# The active half of the session - the page flip, the PRT/NOALLOC holder, two concurrent clients,
# the SDMA paging copy - is NOT here. It needs flip.py, e17_vm.py, pt_walk.py, dispatch.py and
# paging.py, and it is planned in scratch/tmp/linux_session_plan.md phases 8 to 13.

set -u

STAMP=$(date -u +%Y%m%dT%H%M%SZ)
OUT=${BC250_OUT:-/tmp/bc250-$STAMP}
HERE=$(cd "$(dirname "$0")" 2>/dev/null && pwd) || HERE=.
T=/sys/kernel/tracing
DBG=/sys/kernel/debug
TEMP_LIMIT_MC=85000            # millidegrees C, the hard limit from <BC250_ROOT>\CLAUDE.md
OVERTEMP="$OUT/OVERTEMP"

mkdir -p "$OUT" "$OUT/rings" "$OUT/dmu"
STEPS="$OUT/steps.log"
CMDS="$OUT/commands.log"
: > "$STEPS"
: > "$CMDS"

say() { echo "== $*"; }

# Every command's exit code, whether it mattered or not. Nothing here ever returns non-zero to the
# caller, so a failing command cannot end a step and a failing step cannot end the run.
note() {
	echo "$1 rc=$2" >> "$CMDS"
	[ "$2" = "0" ] || say "   ! $1 rc=$2"
	return 0
}

have() { [ -r "$1" ]; }

need() {
	if have "$HERE/$1"; then
		return 0
	fi
	say "   SKIP: $HERE/$1 was not pushed"
	echo "missing $1" >> "$CMDS"
	return 1
}

# Each of these prints nothing at all when there is no match. `dirname ""` answers "." , which would
# make every `[ -n "$D" ]` below pass with a wrong path, so the empty case is caught first.
parent_of() {
	p=$1
	[ -n "$p" ] || return 1
	dirname "$p"
}
gpu() { lspci -D -d 1002:13fe 2>/dev/null | head -1 | cut -d' ' -f1; }
dri() { parent_of "$(ls "$DBG"/dri/*/amdgpu_regs2 2>/dev/null | head -1)"; }
dev() { parent_of "$(ls -d /sys/class/drm/card*/device/mem_info_vram_total 2>/dev/null | head -1)"; }
media() { parent_of "$(ls /media/*/bc250/sweep_stream.py 2>/dev/null | head -1)"; }

debugfs_up() {
	mountpoint -q "$DBG" || mount -t debugfs nodev "$DBG"
	note "mount debugfs" $?
}

tracefs_up() {
	mountpoint -q $T || mount -t tracefs nodev $T
	note "mount tracefs" $?
}

# Temperature before and after anything that could warm the part, and at the end of every step.
# Above 85 C the script refuses to start further steps; it does not kill a step that is running,
# and `close` always runs.
temp() {
	d=$(dev)
	[ -n "$d" ] || { echo "no drm device yet"; return 0; }
	for f in "$d"/hwmon/hwmon*/temp1_input; do
		[ -r "$f" ] || continue
		mc=$(cat "$f" 2>/dev/null)
		# A non-numeric reading would make the comparison below an error, not a false: drop it.
		case "$mc" in ""|*[!0-9]*) continue ;; esac
		echo "$mc" | awk '{printf "edge %.1f C\n", $1 / 1000}'
		if [ "$mc" -ge "$TEMP_LIMIT_MC" ]; then
			say "   STOP: edge temperature is at or above 85 C - no further step will start"
			echo "$mc" > "$OVERTEMP"
		fi
	done
	cat "$d"/hwmon/hwmon*/power1_input "$d"/hwmon/hwmon*/power1_average 2>/dev/null
	cat "$d"/pp_dpm_sclk 2>/dev/null
	return 0
}

# E13's arm/disarm, unchanged, so a trace taken here compares with E03's, E13's and E14's line for
# line. tracefs is the one thing outside the output directory this script writes to, and disarm
# puts it back.
arm() {
	tracefs_up
	echo 0 > $T/tracing_on
	echo 65536 > $T/buffer_size_kb
	echo > $T/trace
	echo ':mod:amdgpu' > $T/set_event 2>/dev/null || echo 'amdgpu:*' > $T/set_event
	echo 1 > $T/tracing_on
	echo "bc250 begin $1" > $T/trace_marker
	note "arm $1" $?
}

disarm() {
	echo "bc250 end $1" > $T/trace_marker
	echo 0 > $T/tracing_on
	cat $T/trace > "$OUT/$2"
	note "disarm $1 -> $2" $?
	say "   trace $2: $(wc -l < "$OUT/$2" 2>/dev/null) lines; overruns: $(cat $T/per_cpu/cpu*/stats 2>/dev/null \
		| awk '/overrun|dropped/ {s+=$2} END {print s+0}')"
	echo > $T/set_event
	echo > $T/trace
}

# ------------------------------------------------------------------------------- steps

step_pre() {
	say "kernel and boot"
	uname -a; note "uname" $?
	cat /proc/cmdline; note "cmdline" $?
	case "$(cat /proc/cmdline 2>/dev/null)" in
		*bc250.mode=readonly*) say "   mode readonly: no MMIO write will be made by the stick" ;;
		*) say "   WARNING: this is not the bc250.mode=readonly entry - check grub.cfg" ;;
	esac
	say "boot history is the owner's to tell: cold or warm. uptime:"
	uptime; note "uptime" $?
	say "amdgpu loaded? (empty is what this step wants)"
	lsmod | grep -i amdgpu; note "lsmod amdgpu (1 = absent, which is right here)" $?
	say "memory: the whole session lives in RAM"
	head -4 /proc/meminfo; df -h /tmp | tail -1
	say "PCI view"
	lspci -nn > "$OUT/lspci.txt" 2>&1; note "lspci -nn" $?
	head -20 "$OUT/lspci.txt"
	G=$(gpu)
	say "GPU function $G"
	lspci -vvv -s "$G" > "$OUT/lspci-gpu.txt" 2>&1; note "lspci -vvv gpu" $?
	say "PSP/CCP function 1022:143e (wishlist L13, already answered - a cheap re-check)"
	lspci -vvv -d 1022:143e > "$OUT/lspci-ccp.txt" 2>&1; note "lspci -vvv ccp" $?
	say "M.2 root port 00:15.0 (wishlist L12: only a row if this boot's warm/cold state is recorded)"
	lspci -vvv -s 00:15.0 2>/dev/null | grep -E 'LnkSta|LnkCtl2|UESta|CESta|DevSta' \
		| head -20 | tee "$OUT/m2-port.txt"
	note "m2 root port" $?
	say "interrupts"
	grep -E 'CPU0|amdgpu' /proc/interrupts > "$OUT/interrupts-pre.txt" 2>&1; note "interrupts" $?
	cat "$OUT/interrupts-pre.txt"
	return 0
}

step_sweep() {
	M=$(media)
	[ -n "$M" ] || { say "   SKIP: sweep_stream.py not found under /media/*/bc250"; return 1; }
	spec=""
	for c in "$HERE/sweep.json" "$M/sweep.json"; do
		have "$c" && { spec=$c; break; }
	done
	[ -n "$spec" ] || { say "   SKIP: sweep.json was not pushed"; return 1; }
	skip=""
	have "$HERE/skip-conservative.txt" && skip="--skip $HERE/skip-conservative.txt"
	[ -n "$skip" ] || say "   WARNING: no skip list - E03 hung this machine on MMHUB.MMEA0_ADDRDEC0_BASE_ADDR_CS0"
	say "pre-driver sweep, streamed: the last unfinished line is the register that hung us"
	# shellcheck disable=SC2086
	python3 -u "$M/sweep_stream.py" "$spec" $skip > "$OUT/sweep-pre.log" 2>&1
	note "sweep_stream pre-driver" $?
	say "   $(wc -l < "$OUT/sweep-pre.log") lines"
	head -2 "$OUT/sweep-pre.log"
	say "positive control: the two values every later reading is checked against"
	grep -E 'GC\.(GB_ADDR_CONFIG|CC_GC_SHADER_ARRAY_CONFIG) ' "$OUT/sweep-pre.log"
	note "control GB_ADDR_CONFIG / CC_GC_SHADER_ARRAY_CONFIG" $?
	return 0
}

step_dmupre() {
	# The highest-risk read of the session: about seventy BAR5 addresses in the display block that
	# no method has ever read on this unit. DCHUB is clocked - the firmware has a picture on the
	# screen - which is the argument that they are safe. It is an argument, not a measurement, so
	# this goes through the streaming reader like every other first read.
	M=$(media)
	[ -n "$M" ] || { say "   SKIP: sweep_stream.py not found"; return 1; }
	need dmusweep.json || return 1
	say "the FIRMWARE's DMU state, raw BAR5, before any driver exists (wishlist L21)"
	python3 -u "$M/sweep_stream.py" "$HERE/dmusweep.json" --order DMU \
		> "$OUT/dmu/dmu-pre.log" 2>&1
	note "sweep_stream DMU pre-driver" $?
	cat "$OUT/dmu/dmu-pre.log"
	say "which HUBP holds a non-zero surface address - that is the pipe the firmware lit"
	grep -E 'DCSURF_PRIMARY_SURFACE_ADDRESS|DCSURF_SURFACE_INUSE|DCHUBP_CNTL|OTG._OTG_CONTROL' \
		"$OUT/dmu/dmu-pre.log" | grep -vE ' 00000000$'
	note "dmu non-zero filter" $?
	say "compare those against the firmware framebuffer's MC address on the PC (L21's control)"
	return 0
}

step_load() {
	if lsmod | grep -qi '^amdgpu'; then
		say "   SKIP: amdgpu is already loaded. A second modprobe in one boot hangs this machine (M55)"
		return 1
	fi
	tracefs_up
	# The SMU message probe is armed here and stays armed for the rest of the boot: swsmu has no
	# tracepoint, so a kprobe on the send function is the only way to see what amdgpu asks the SMU.
	# It READS; it sends nothing. If the symbol was inlined by this kernel build the echo fails,
	# which is logged and is itself the answer to that open question.
	echo 'p:smumsg amdgpu:smu_cmn_send_smc_msg_with_param msg=$arg2:x32 param=$arg3:x32' \
		>> $T/kprobe_events 2>>"$OUT/kprobe-errors.txt"
	note "kprobe smu_cmn_send_smc_msg_with_param" $?
	arm load
	echo 1 > $T/events/kprobes/enable 2>/dev/null; note "enable kprobes" $?
	say "modprobe amdgpu $(date -u +%H:%M:%SZ)"
	modprobe amdgpu; note "modprobe amdgpu" $?
	i=0
	while [ $i -lt 60 ]; do
		dmesg 2>/dev/null | grep -q 'Initialized amdgpu' && break
		sleep 1
		i=$((i + 1))
	done
	say "   waited ${i}s for 'Initialized amdgpu'"
	sleep 3
	disarm load amdgpu-events-load.txt
	dmesg | grep -i amdgpu | tail -8
	say "register writes in the init trace (E03 saw 10018)"
	grep -c 'amdgpu_device_wreg' "$OUT/amdgpu-events-load.txt"
	note "wreg count" $?
	say "temperature"; temp
	return 0
}

step_state() {
	debugfs_up
	D=$(dri); DEV=$(dev)
	[ -n "$D" ] || { say "   SKIP: no amdgpu_regs2 - debugfs not mounted or amdgpu not loaded"; return 1; }
	say "debugfs dir $D, device dir $DEV"
	say "dmesg, module parameters, modinfo (wishlist L15, a re-check)"
	dmesg > "$OUT/dmesg.txt" 2>&1; note "dmesg" $?
	grep . /sys/module/amdgpu/parameters/* > "$OUT/module-parameters.txt" 2>&1; note "module params" $?
	modinfo amdgpu > "$OUT/modinfo.txt" 2>&1; note "modinfo" $?
	say "interrupts and MSI state (L11, already MEASURED as M40 - this confirms the boot matches)"
	grep -E 'CPU0|amdgpu' /proc/interrupts > "$OUT/interrupts-post.txt" 2>&1; note "interrupts post" $?
	cat "$OUT/interrupts-post.txt"
	lspci -vvv -s "$(gpu)" > "$OUT/lspci-gpu-post.txt" 2>&1; note "lspci gpu post" $?
	say "firmware versions and the hashes of the files in use (L3)"
	cat "$D/amdgpu_firmware_info" > "$OUT/firmware_info.txt" 2>&1; note "firmware_info" $?
	head -8 "$OUT/firmware_info.txt"
	sha256sum /lib/firmware/amdgpu/cyan_skillfish2_*.bin > "$OUT/firmware-sha256.txt" 2>&1
	note "firmware sha256" $?
	say "memory managers and totals (L7)"
	head -40 "$D/amdgpu_vram_mm" > "$OUT/vram_mm.txt" 2>&1; note "vram_mm" $?
	head -60 "$D/amdgpu_gtt_mm" > "$OUT/gtt_mm.txt" 2>&1; note "gtt_mm" $?
	cat "$DEV"/mem_info_* > "$OUT/mem_info.txt" 2>&1; note "mem_info" $?
	head -8 "$OUT/vram_mm.txt"
	say "rings and MQDs as 32-bit words -> $OUT/rings (busybox od alone reads nothing from these"
	say "files; dd bs=4096 | od does - measured in E13)"
	for f in "$D"/amdgpu_ring_* "$D"/amdgpu_mqd_*; do
		[ -e "$f" ] || continue
		b=$(basename "$f")
		dd if="$f" bs=4096 2>/dev/null | od -A x -t x4 -v > "$OUT/rings/$b.txt"
		note "dump $b" $?
	done
	ls "$OUT/rings" | wc -l
	say "named registers through amdgpu's own accessor (regs2.py, read-only, under amdgpu's mutex)"
	if need regs2.py && need lists.json; then
		python3 -u "$HERE/regs2.py" "$HERE/lists.json" state > "$OUT/regs-state.txt" 2>&1
		note "regs2 state" $?
		python3 -u "$HERE/regs2.py" "$HERE/lists.json" hqd > "$OUT/regs-hqd.txt" 2>&1
		note "regs2 hqd" $?
		say "positive control: M40's idle values must come back"
		grep -E '^(IH_RB_CNTL|IH_CNTL|IH_DOORBELL_RPTR|CP_INT_CNTL_RING0) ' "$OUT/regs-state.txt"
		note "control M40 idle values" $?
	fi
	say "temperature"; temp
	return 0
}

step_dmupost() {
	debugfs_up
	need regs2.py || return 1
	need dmulists.json || return 1
	say "the same DMU set again, now through amdgpu_regs2: the second method that turns L21 from"
	say "MEASURED into CONFIRMED, or shows one of the two paths to be wrong"
	python3 -u "$HERE/regs2.py" "$HERE/dmulists.json" state > "$OUT/dmu/dmu-post.txt" 2>&1
	note "regs2 dmu" $?
	cat "$OUT/dmu/dmu-post.txt"
	say "amdgpu's own account of the same mode set, for the comparison (L8)"
	D=$(dri)
	[ -n "$D" ] && { cat "$D/amdgpu_dm_dtn_log" > "$OUT/dtn_log.txt" 2>&1; note "dtn log" $?; }
	grep -iE 'otg|hubp|pipe|link|lane|pixel' "$OUT/dtn_log.txt" 2>/dev/null | head -40
	return 0
}

step_vmregs() {
	debugfs_up
	need regs2.py || return 1
	need vmlists.json || return 1
	say "412 named VM registers of both hubs, with no client running (E17's base phase)"
	python3 -u "$HERE/regs2.py" "$HERE/vmlists.json" state > "$OUT/vmregs-base.txt" 2>&1
	note "regs2 vmlists" $?
	say "control (E17's H7): with nothing submitted the context page table bases must still be zero"
	grep -E 'CONTEXT[0-9]+_PAGE_TABLE_BASE_ADDR_LO32|CONTEXT[0-9]+_CNTL ' "$OUT/vmregs-base.txt" | head -20
	note "control CONTEXT bases" $?
	D=$(dri)
	if [ -n "$D" ]; then
		head -120 "$D/amdgpu_vm_info" > "$OUT/vm_info-base.txt" 2>&1; note "vm_info" $?
		head -200 "$D/amdgpu_gem_info" > "$OUT/gem_info-base.txt" 2>&1; note "gem_info" $?
		wc -l "$OUT/vm_info-base.txt" "$OUT/gem_info-base.txt"
	fi
	say "clients amdgpu knows about right now (empty is what this step wants)"
	for d in "$DBG"/dri/client-*; do
		[ -e "$d/proc_info" ] || continue
		echo "-- $(basename "$d") $(tr '\n' ' ' < "$d/proc_info")"
	done
	return 0
}

step_extras() {
	debugfs_up
	D=$(dri); DEV=$(dev)
	[ -n "$DEV" ] || { say "   SKIP: no drm device directory"; return 1; }
	say "ip_discovery in full (wishlist L19) -> ip_discovery.txt"
	if [ -d "$DEV/ip_discovery" ]; then
		find "$DEV/ip_discovery" -type f | sort | while read -r f; do
			echo "${f#"$DEV"/} $(tr '\n' ' ' < "$f" 2>&1)"
		done > "$OUT/ip_discovery.txt"
		note "ip_discovery walk" $?
		wc -l "$OUT/ip_discovery.txt"
		say "hardware id 12 (UVD/VCN), the row L19 was written for"
		grep '/12/' "$OUT/ip_discovery.txt"
		note "ip_discovery id 12" $?
	else
		say "   absent"
	fi
	say "display connectors (L8). EDID is deliberately NOT read"
	for f in /sys/class/drm/card*-DP-*/ /sys/class/drm/card*-HDMI-*/; do
		[ -d "$f" ] || continue
		echo "-- $f status $(cat "$f/status" 2>/dev/null) enabled $(cat "$f/enabled" 2>/dev/null)"
	done > "$OUT/connectors.txt" 2>&1
	note "connectors" $?
	cat "$OUT/connectors.txt"
	say "GDS, GWS and OA; KFD topology"
	cat /sys/class/kfd/kfd/topology/nodes/*/properties > "$OUT/kfd-topology.txt" 2>&1
	note "kfd topology" $?
	grep -iE 'gds|num_gws|array_count|simd|lds' "$OUT/kfd-topology.txt" | head -12
	if [ -n "$D" ]; then
		head -40 "$D/amdgpu_sa_info" > "$OUT/sa_info.txt" 2>&1; note "sa_info" $?
		head -40 "$D/amdgpu_fence_info" > "$OUT/fence_info.txt" 2>&1; note "fence_info" $?
		cat "$OUT/fence_info.txt"
	fi
	say "iomem, for the record"
	cat /proc/iomem > "$OUT/iomem.txt" 2>&1; note "iomem" $?
	return 0
}

step_info() {
	need info.py || return 1
	need info.json || return 1
	say "every AMDGPU_INFO query, raw (E13's info.py unchanged) -> info.txt"
	python3 -u "$HERE/info.py" "$HERE/info.json" > "$OUT/info.txt" 2>&1
	note "info.py" $?
	wc -l "$OUT/info.txt"; head -20 "$OUT/info.txt"
	say "compare with facts M46 on the PC: a difference is a fact to correct, not a surprise"
	return 0
}

step_power() {
	DEV=$(dev); D=$(dri)
	[ -n "$DEV" ] || { say "   SKIP: no drm device directory"; return 1; }
	say "the whole power surface, READ ONLY (wishlist L10, ADR 0010 point 6). Nothing is written"
	for a in pp_dpm_sclk pp_dpm_mclk pp_dpm_fclk pp_dpm_pcie pp_features power_dpm_state \
		power_dpm_force_performance_level pp_power_profile_mode pp_od_clk_voltage \
		gpu_busy_percent vbios_version power_state; do
		echo "-- $a"
		cat "$DEV/$a" 2>&1
	done > "$OUT/power-idle.txt" 2>&1
	note "power sysfs" $?
	cat "$OUT/power-idle.txt"
	say "hwmon"
	for f in "$DEV"/hwmon/hwmon*/*_input "$DEV"/hwmon/hwmon*/*_label; do
		[ -r "$f" ] || continue
		echo "$(basename "$f") $(cat "$f" 2>&1)"
	done > "$OUT/hwmon.txt" 2>&1
	note "hwmon" $?
	cat "$OUT/hwmon.txt"
	if [ -n "$D" ]; then
		cat "$D/amdgpu_pm_info" > "$OUT/pm_info.txt" 2>&1; note "amdgpu_pm_info" $?
		cat "$OUT/pm_info.txt"
		dd if="$DEV/gpu_metrics" bs=4096 2>/dev/null | od -A x -t x1 -v > "$OUT/gpu_metrics.txt"
		note "gpu_metrics raw" $?
	fi
	say "the SMU messages amdgpu itself sent this boot, off the kprobe armed in the load step"
	if [ -r $T/trace ]; then
		grep smumsg $T/trace > "$OUT/smu-msgs.txt" 2>&1
		note "smu kprobe buffer" $?
		wc -l "$OUT/smu-msgs.txt"; head -20 "$OUT/smu-msgs.txt"
		say "every message number here must exist in cyan_skillfish_ppt.c - one that does not is"
		say "the interesting result (our Windows allow-list, facts M22, was built from that file)"
	else
		say "   tracefs is not mounted: no kprobe buffer to read"
	fi
	say "temperature"; temp
	return 0
}

step_close() {
	say "temperature and clocks"
	temp
	say "kernel log tail"
	dmesg | tail -60 > "$OUT/dmesg-tail.txt" 2>&1; note "dmesg tail" $?
	cat "$OUT/dmesg-tail.txt"
	say "anything that must stop the session"
	grep -E 'VM_L2_PROTECTION_FAULT|ring .* timeout|GPU reset|hang' "$OUT/dmesg.txt" "$OUT/dmesg-tail.txt" 2>/dev/null | head
	note "hang scan (1 = nothing found, which is right)" $?
	say "kprobes put back"
	if [ -w $T/kprobe_events ]; then
		echo 0 > $T/events/kprobes/enable 2>/dev/null
		echo > $T/kprobe_events 2>/dev/null
		note "kprobe_events cleared" $?
	fi
	say "inventory"
	uptime; df -h /tmp | tail -1
	find "$OUT" -type f | wc -l
	du -sh "$OUT" 2>/dev/null
	say "steps:"
	cat "$STEPS"
	return 0
}

# ------------------------------------------------------------------------------- driver

ALL="pre sweep dmupre load state dmupost vmregs extras info power close"

run_step() {
	name=$1
	if ! command -v "step_$name" >/dev/null 2>&1 && ! type "step_$name" >/dev/null 2>&1; then
		say "---- unknown step $name"
		echo "$name rc=127 SKIPPED-unknown" >> "$STEPS"
		return 0
	fi
	if [ -f "$OVERTEMP" ] && [ "$name" != "close" ]; then
		say "---- $name SKIPPED: the 85 C limit was reached"
		echo "$name rc=- SKIPPED-overtemp" >> "$STEPS"
		return 0
	fi
	t0=$(date +%s)
	say "---- step $name start $(date -u +%H:%M:%SZ)"
	{ "step_$name"; echo $? > "$OUT/.rc"; } 2>&1 | tee "$OUT/$name.txt"
	rc=$(cat "$OUT/.rc" 2>/dev/null || echo 126)
	t1=$(date +%s)
	echo "$name rc=$rc secs=$((t1 - t0))" >> "$STEPS"
	say "---- step $name rc=$rc after $((t1 - t0))s"
	return 0
}


What is in here that must not reach the repository:
  - MAC addresses (dmesg.txt, lspci-*.txt, interrupts, anything the network came up in)
  - the Wi-Fi SSID and anything of wpa_supplicant (dmesg.txt)
  - board and USB serial numbers, UUIDs (dmesg.txt, lspci-*.txt, iomem.txt, ip_discovery.txt)
  - the EDID, which this script does not read on purpose - check anyway
Firmware blobs and ACPI tables are not captured here and stay outside the repository in any case.
EOF


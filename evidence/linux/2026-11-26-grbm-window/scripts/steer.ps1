# Generated: stick-env.ps1 of kit r9 + stick functions of Cks.Route.ps1 (hlk-cks-kit-r1) + the steer body.
# Pure functions for the GRUB environment block (grubenv, exactly 1024 bytes) of the signed lab stick.
# Windows PowerShell 5.1 and PowerShell 7. No IO, registry, process or hardware access on import.
# The signed grub.cfg reads only the names below and only compares their values with fixed words
# (make_grub_cfg.py). These functions refuse every other name and every value outside the rule of its name, so
# a tool that uses them cannot write a line that the menu does not know.
# No Set-StrictMode here: the listener dot-sources this file, and the mode would change the listener's own scope.

$script:StickEnvHeader = "# GRUB Environment Block`n"
# GRUB 2.12 and newer write this second comment line into a new block. It is kept when it is there.
$script:StickEnvWarning = "# WARNING: Do not edit this file by tools other than grub-editenv!!!`n"
$script:StickEnvRules = [ordered]@{
    bc250_default      = '^[0-5]$'            # a Linux entry; no variable means Windows
    bc250_try          = '^[123]$'            # the X3 start counter (written by GRUB; tools only clear it)
    bc250_stage_left   = '^[012]$'            # armed starts of the EFI stage
    bc250_stage_set    = '^[a-z0-9]{1,16}$'   # NAME of a signed option set for the armed starts
    bc250_stage_always = '^[a-z0-9]{1,16}$'   # NAME of a signed option set for every Windows start
    bc250_tool_left    = '^[0-5]$'            # armed starts of a signed EFI tool (GRUB counts down)
    bc250_tool         = '^[a-z0-9]{1,16}$'   # NAME of a signed EFI tool for the armed start
bc250_tool_always  = '^[a-z0-9]{1,16}$'   # NAME of a signed EFI tool for every Windows start
}

# Returns @{ Warning = <bool>; Table = <ordered table name -> value> }. Throws when the block is not well-formed.
function Read-StickEnvParts([byte[]]$Bytes) {
    if ($null -eq $Bytes -or $Bytes.Length -ne 1024) { throw 'grubenv must be exactly 1024 bytes' }
    foreach ($b in $Bytes) {
        if ($b -ne 10 -and ($b -lt 32 -or $b -gt 126)) { throw 'grubenv has a non-ASCII or control byte' }
    }
    $text = [Text.Encoding]::ASCII.GetString($Bytes)
    if (-not $text.StartsWith($script:StickEnvHeader, [StringComparison]::Ordinal)) { throw 'invalid grubenv header' }
    $rest = $text.Substring($script:StickEnvHeader.Length)
    $warning = $rest.StartsWith($script:StickEnvWarning, [StringComparison]::Ordinal)
    if ($warning) { $rest = $rest.Substring($script:StickEnvWarning.Length) }
    $table = [ordered]@{}
    while (-not ($rest -cmatch '^#+$')) {
        $m = [regex]::Match($rest, '\A([A-Za-z_][A-Za-z0-9_]*)=([^\r\n]*)\n')
        if (-not $m.Success) { throw 'invalid grubenv variable or padding' }
        if ($table.Contains($m.Groups[1].Value)) { throw 'duplicate grubenv variable' }
        $table[$m.Groups[1].Value] = $m.Groups[2].Value
        $rest = $rest.Substring($m.Length)
    }
    return @{ Warning = $warning; Table = $table }
}

# Returns an ordered table name -> value. Throws when the block is not a well-formed 1024-byte block.
function Read-StickEnv([byte[]]$Bytes) { return (Read-StickEnvParts $Bytes).Table }

# Returns the 1024 bytes of a block with the lines of $Table, in the order of $Table.
function Format-StickEnv($Table, [bool]$Warning = $false) {
    $text = $script:StickEnvHeader
    if ($Warning) { $text += $script:StickEnvWarning }
    foreach ($name in $Table.Keys) { $text += "$name=$($Table[$name])`n" }
    if ($text.Length -ge 1024) { throw 'grubenv has no padding space' }
    return ,[Text.Encoding]::ASCII.GetBytes($text + ('#' * (1024 - $text.Length)))
}

# Returns new block bytes with $Name set to $Value, or removed when $Value is $null or ''.
# Lines with other names stay as they are, in their order. A new name goes to the end.
function Set-StickEnvValue([byte[]]$Bytes, [string]$Name, [string]$Value) {
    if (-not $script:StickEnvRules.Contains($Name)) { throw "grubenv name '$Name' is not one that the signed menu reads" }
    $parts = Read-StickEnvParts $Bytes
    $table = $parts.Table
    if ([string]::IsNullOrEmpty($Value)) {
        if ($table.Contains($Name)) { $table.Remove($Name) }
    } else {
        if ($Name -ceq 'bc250_try') { throw 'bc250_try is written by GRUB; a tool can only clear it' }
        if ($Value -cnotmatch $script:StickEnvRules[$Name]) { throw "value '$Value' is not valid for $Name" }
        $table[$Name] = $Value
    }
    return ,(Format-StickEnv $table $parts.Warning)
}

# A new empty block (the form that `grub-editenv create` of GRUB 2.14 writes).
function New-StickEnv { return ,(Format-StickEnv ([ordered]@{}) $true) }
function Get-CksStickLoader([string]$Root) {
    $on = [IO.File]::Exists($Root + 'efi\boot\bootx64.efi')
    $off = [IO.File]::Exists($Root + 'efi\boot\bootx64.off')
    if ($on -and $off) { return 'both' }
    if ($on) { return 'on' }
    if ($off) { return 'off' }
    return 'missing'
}

# Renames the loader between its two names and reads the state back. No file content is written.
function Set-CksStickLoader([string]$Root, [bool]$On) {
    $want = $(if ($On) { 'on' } else { 'off' })
    $state = Get-CksStickLoader $Root
    if ($state -ceq $want) { return $state }
    if ($state -cnotin @('on', 'off')) { throw "The stick loader state is '$state': nothing renamed. Read efi\boot of the stick first." }
    if ($On) { [IO.File]::Move($Root + 'efi\boot\bootx64.off', $Root + 'efi\boot\bootx64.efi') }
    else { [IO.File]::Move($Root + 'efi\boot\bootx64.efi', $Root + 'efi\boot\bootx64.off') }
    $after = Get-CksStickLoader $Root
    if ($after -cne $want) { throw "The stick loader state is '$after' after the rename." }
    return $after
}

function Get-CksStick([string]$Label, [string]$Marker) {
    $r = @{ Count = 0; Root = ''; Letter = ''; FileSystem = ''; BusType = ''; Size = [uint64]0; MarkerPresent = $false; Loader = '' }
    $vols = @(Get-Volume -FileSystemLabel $Label -ErrorAction SilentlyContinue)
    $r.Count = $vols.Count
    if ($vols.Count -ne 1) { return $r }
    $v = $vols[0]
    $letter = [string]$v.DriveLetter
    if ($letter -match '^[A-Za-z]$') { $r.Letter = $letter; $r.Root = $letter + ':\' } else { $r.Root = [string]$v.Path }
    $r.FileSystem = [string]$v.FileSystem
    $r.Size = [uint64]$v.Size
    $part = @(Get-Partition -ErrorAction SilentlyContinue | Where-Object { @($_.AccessPaths) -contains $v.Path }) | Select-Object -First 1
    if ($part) { $r.BusType = [string](Get-Disk -Number $part.DiskNumber).BusType }
    if ($r.Root) { $r.MarkerPresent = [IO.File]::Exists($r.Root + $Marker); $r.Loader = Get-CksStickLoader $r.Root }
    return $r
}

function Test-CksStickOk($Stick, [uint64]$ExpectedSize) {
    return ([int]$Stick.Count -eq 1 -and [string]$Stick.FileSystem -ceq 'FAT32' -and [string]$Stick.BusType -ceq 'USB' -and
        [bool]$Stick.MarkerPresent -and ($ExpectedSize -eq 0 -or [uint64]$Stick.Size -eq $ExpectedSize))
}

function Read-CksEnvBytes([string]$Root) { return ,([IO.File]::ReadAllBytes($Root + 'boot\grub\grubenv')) }

# Writes the 1024-byte block in place (the file keeps its length and its blocks), through the cache to the
# medium, then reads it back and compares.
function Write-CksEnvBytes([string]$Root, [byte[]]$Bytes) {
    [void](Read-StickEnv $Bytes)
    $p = $Root + 'boot\grub\grubenv'
    if ((New-Object IO.FileInfo $p).Length -ne 1024) { throw 'the grubenv file on the stick is not 1024 bytes' }
    $fs = New-Object IO.FileStream($p, [IO.FileMode]::Open, [IO.FileAccess]::Write, [IO.FileShare]::None, 4096, [IO.FileOptions]::WriteThrough)
    try { $fs.Write($Bytes, 0, $Bytes.Length); $fs.Flush($true) } finally { $fs.Dispose() }
    $back = [IO.File]::ReadAllBytes($p)
    if ($back.Length -ne $Bytes.Length) { throw 'the grubenv read back has another length' }
    for ($i = 0; $i -lt $back.Length; $i++) { if ($back[$i] -ne $Bytes[$i]) { throw 'the grubenv read back differs from the written block' } }
}


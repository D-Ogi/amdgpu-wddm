# Writes vrsprobe_spv.h: the four SPIR-V modules of vrsprobe as uint32_t arrays.
# Usage: python gen_spv_header.py <out.h> name=file.spv [name=file.spv ...]
import hashlib
import struct
import sys

out = sys.argv[1]
lines = ['/* Generated by gen_spv_header.py from the glslc output of vrsprobe.vert and vrsprobe.frag. */', '#pragma once',
         '#include <stdint.h>', '']
for arg in sys.argv[2:]:
    name, path = arg.split('=', 1)
    data = open(path, 'rb').read()
    if len(data) % 4 or struct.unpack_from('<I', data)[0] != 0x07230203:
        sys.exit('%s is not a SPIR-V module' % path)
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    lines.append('/* %s: %d bytes, sha256 %s */' % (path.replace('\\', '/').split('/')[-1], len(data),
                                                  hashlib.sha256(data).hexdigest()))
    lines.append('static const uint32_t %s[%d] = {' % (name, len(words)))
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    lines.append('};')
    lines.append('')
open(out, 'w', newline='\n').write('\n'.join(lines))
print('wrote', out)
